#!/usr/bin/env node
// Получение средств слоя B по ходункам проекта.
//
// Скрипт не копирует исходники инструментов в проект: он забирает готовые
// выпуски из реестра пакетов и раскладывает их в локальный каталог, который
// не версионируется. Состав средств — ходунки проекта,
// ИНСТРУМЕНТЫ/training-wheels.json.
//
// Команды:
//   node ИНСТРУМЕНТЫ/скрипты/инструменты.mjs проверить    что есть, чего нет
//   node ИНСТРУМЕНТЫ/скрипты/инструменты.mjs план         какие адреса будут вызваны
//   node ИНСТРУМЕНТЫ/скрипты/инструменты.mjs установить [идентификатор ...]
//
// Ключ --строго переводит отсутствие обязательного средства в ненулевой код
// возврата: так гейт CI отличает «средство не настроено» от «проверка пройдена».
// Под ним же роняет прогон отставание ходунков от реестра: иначе проект узнаёт о
// нём только от того, кто вспомнил сверить версии руками.
//
// Ключ --без-сети снимает сверку с реестром: в закрытом контуре и в прогоне без
// токена обращаться некуда, и тишина об этом честнее выдуманного «актуально».
//
// Переменная TRIP_TOOLS_REGISTRY_BASE подменяет адрес реестра — для зеркала
// закрытого контура и для самопроверки.

import { readFileSync, mkdirSync, writeFileSync, existsSync, rmSync } from 'node:fs';
import { execFileSync } from 'node:child_process';
import { createHash } from 'node:crypto';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const КОРЕНЬ = resolve(dirname(fileURLToPath(import.meta.url)), '..', '..');
const ПУТЬ_ХОДУНКОВ = join(КОРЕНЬ, 'ИНСТРУМЕНТЫ', 'training-wheels.json');

const аргументы = process.argv.slice(2);
const команда = аргументы.find((а) => !а.startsWith('--')) ?? 'проверить';
const строго = аргументы.includes('--строго');
const безСети = аргументы.includes('--без-сети');
const отобранные = аргументы.filter((а) => !а.startsWith('--') && а !== команда);

/** Незаполненный плейсхолдер вида <что-то> отличается от настроенного значения. */
const плейсхолдер = (значение) => typeof значение === 'string' && /^<.*>$/.test(значение.trim());

function прочитатьХодунки() {
  if (!existsSync(ПУТЬ_ХОДУНКОВ)) {
    throw new Error(`Ходунки средств не найдены: ${ПУТЬ_ХОДУНКОВ}`);
  }
  return JSON.parse(readFileSync(ПУТЬ_ХОДУНКОВ, 'utf8'));
}

// Сборка под чужую архитектуру не подставляется даже там, где её выполнил бы
// слой совместимости: подмена молча выглядит как «всё есть», а отказ приходит
// позже и не отсюда. Нет выпуска под платформу — это состояние поставки, и
// говорить о нём надо прямо.
//
// TRIP_TARGET_PLATFORM отвечает на вопрос «что получит коллега на другой
// машине», не заводя эту машину. Значение разбирается, а не принимается на
// веру: опечатка вроде «macos-arm64» дала бы честное с виду «выпуск под
// macos-arm64 не публикуется», и спрашивавший решил бы, что сборок под macOS
// нет, — ответ на вопрос, которого он не задавал.
const ПЛАТФОРМЫ = ['win-x64', 'win-arm64', 'linux-x64', 'linux-arm64', 'darwin-x64', 'darwin-arm64'];

function своя() {
  const арх = process.arch === 'arm64' ? 'arm64' : 'x64';
  if (process.platform === 'win32') return `win-${арх}`;
  if (process.platform === 'darwin') return `darwin-${арх}`;
  return `linux-${арх}`;
}

function платформа() {
  const заданная = process.env.TRIP_TARGET_PLATFORM;
  if (!заданная) return своя();
  if (!ПЛАТФОРМЫ.includes(заданная)) {
    throw new Error(
      `TRIP_TARGET_PLATFORM=${заданная} — неизвестная платформа. Допустимы: ${ПЛАТФОРМЫ.join(', ')}.`,
    );
  }
  return заданная;
}

/** Средство, распакованное под проект: каталог ходунков с манифестом внутри. */
function ужеВПроекте(ходунки, средство) {
  const дом = join(КОРЕНЬ, ходунки.install_root, средство.id);
  return existsSync(join(дом, 'tool-manifest.json')) || existsSync(дом);
}

function уженВСистеме(средство) {
  const проверка = средство.already_installed_check;
  if (!проверка) return null;
  const [команда, ...остальное] = проверка.split(' ');
  try {
    // На Windows глобальные команды npm — это .cmd-обёртки, которые запускаются
    // только через командную оболочку.
    execFileSync(команда, остальное, { stdio: 'pipe', timeout: 15000, shell: process.platform === 'win32' });
    return true;
  } catch {
    return false;
  }
}

function адресВыпуска(ходунки, средство) {
  const источник = средство.source ?? {};
  const реестр = ходунки.registries?.[источник.registry];
  if (!реестр) return { ошибка: `реестр «${источник.registry}» не описан в ходунках` };
  if (плейсхолдер(источник.project)) return { ошибка: 'адрес репозитория средства не указан' };
  const проект = encodeURIComponent(источник.project);
  const база = реестр.base_url.replace(/\/+$/, '');

  if (источник.kind === 'generic-package') {
    if (плейсхолдер(средство.version)) return { ошибка: 'версия средства не закреплена' };
    const своя = платформа();
    const ключ = источник.files?.[своя] ? своя : источник.files?.any ? 'any' : null;
    const файл = ключ ? источник.files[ключ] : null;
    if (!файл) {
      // Формулировка важна: «файл выпуска не описан» звучит как промах ходунков и
      // зовёт дописать строку, которой неоткуда взяться. Средство не публикует
      // выпуск под эту платформу вовсе, и решение принимается в его сборке.
      const объявлены = Object.keys(источник.files ?? {}).sort().join(', ');
      return {
        ошибка: `выпуск под ${своя} не публикуется` +
          (объявлены ? `; собирается под: ${объявлены}` : '; файлы выпуска в ходунках не объявлены'),
      };
    }
    const адрес = `${база}/api/v4/projects/${проект}/packages/generic/${источник.package}/${средство.version}/${файл}`;
    return { адрес, файл, реестр, ключ };
  }

  if (источник.kind === 'job-artifact') {
    const адрес = `${база}/api/v4/projects/${проект}/jobs/artifacts/${encodeURIComponent(источник.ref)}` +
      `/download?job=${encodeURIComponent(источник.job)}`;
    return { адрес, файл: `${средство.id}-artifacts.zip`, реестр };
  }

  if (источник.kind === 'npm-registry') {
    return { ошибка: 'ставится через npm: настройте реестр пакетов npm и выполните установку вручную' };
  }
  if (источник.kind === 'container-image') {
    return { ошибка: 'поставляется образом: разворачивается средствами эксплуатации, не этим скриптом' };
  }
  return { ошибка: `неизвестный вид источника «${источник.kind}»` };
}

function заголовкиДоступа(реестр) {
  // Вид проверяется раньше самого токена намеренно. Ошибка в виде — это ошибка
  // настройки, и она видна независимо от того, задан ли токен; проверь мы
  // сначала токен, участник завёл бы его, перезапустил и только тогда узнал бы
  // про вторую половину настройки. Один заход вместо двух.
  //
  // Незнакомое значение не угадывается. Раньше всё, кроме private и job, молча
  // считалось deploy: переменная, в которую вписали имя пользователя токена
  // развёртывания или опечатку, работала «сама собой», и ошибка оставалась в
  // настройках до первого случая, когда угаданный заголовок окажется не тем.
  const ЗАГОЛОВКИ = { deploy: 'DEPLOY-TOKEN', private: 'PRIVATE-TOKEN', job: 'JOB-TOKEN' };
  const вид = (process.env[реестр.token_kind_env] || реестр.token_kind_default || 'deploy').toLowerCase();
  const имя = ЗАГОЛОВКИ[вид];
  if (!имя) {
    throw new Error(
      `${реестр.token_kind_env}=${вид} — неизвестный вид токена. Допустимы: ` +
      `${Object.keys(ЗАГОЛОВКИ).join(', ')}. В эту переменную идёт вид, а не имя пользователя ` +
      'токена развёртывания: установщику нужно только значение.',
    );
  }
  const токен = process.env[реестр.token_env];
  if (!токен) {
    throw new Error(
      `Переменная ${реестр.token_env} не задана. Токен на чтение реестра пакетов выдаёт ` +
      'администратор; личная учётная запись участнику не нужна.',
    );
  }
  // Заголовок запроса — латиница: символ вне её диапазона роняет fetch
  // сообщением про ByteString и индекс символа, по которому участник не
  // догадается, что дело в значении переменной. Чаще всего это скопированное
  // с переносом значение или случайная кириллица в токене.
  if (/[^	 -~]/.test(токен)) {
    throw new Error(
      `Переменная ${реестр.token_env} содержит символ вне латиницы: заголовок запроса ` +
      'такое значение не принимает. Проверьте, что скопирован сам токен, без кавычек, ' +
      'пробелов и переносов строки.',
    );
  }
  return { [имя]: токен };
}

async function скачать(адрес, заголовки, назначение) {
  const ответ = await fetch(адрес, { headers: заголовки, redirect: 'follow' });
  if (!ответ.ok) {
    throw new Error(`${ответ.status} ${ответ.statusText} при обращении к ${адрес}`);
  }
  const данные = Buffer.from(await ответ.arrayBuffer());
  writeFileSync(назначение, данные);
  return createHash('sha256').update(данные).digest('hex');
}

function распаковать(каталог, файлАрхива, каталогЦели) {
  // tar входит в состав Windows 10+ и разбирает как tar.gz, так и zip.
  // Пути даются относительными от рабочего каталога: в двоеточии после буквы
  // диска tar из состава GNU (Git Bash) видит имя удалённого узла и уходит в
  // сеть вместо файла.
  execFileSync('tar', ['-xf', файлАрхива, '-C', каталогЦели], { stdio: 'inherit', cwd: каталог });
}

/**
 * Сравнение версий по числовым участкам через точку: 0.10.0 старше 0.9.0.
 * Порядок реестра для этого не годится — он сортирует строками, и там 0.9.0
 * оказывается старше 0.10.0, то есть «последним выпуском» объявляется прошлый.
 * Непустой хвост после дефиса считается предвыпуском и уступает голому числу.
 */
function сравнитьВерсии(а, б) {
  const разобрать = (версия) => {
    const [ядро, хвост] = String(версия).split('-', 2);
    return { числа: ядро.split('.').map((ч) => (/^\d+$/.test(ч) ? Number(ч) : 0)), хвост };
  };
  const первая = разобрать(а);
  const вторая = разобрать(б);
  const длина = Math.max(первая.числа.length, вторая.числа.length);
  for (let и = 0; и < длина; и += 1) {
    const разница = (первая.числа[и] ?? 0) - (вторая.числа[и] ?? 0);
    if (разница !== 0) return разница < 0 ? -1 : 1;
  }
  if (первая.хвост === вторая.хвост) return 0;
  if (!первая.хвост) return 1;
  if (!вторая.хвост) return -1;
  return первая.хвост < вторая.хвост ? -1 : 1;
}

/** Адрес списка выпусков пакета; null — сверять нечего или незачем. */
function адресПакетов(ходунки, средство) {
  const источник = средство.source ?? {};
  if (источник.kind !== 'generic-package') return null;
  const реестр = ходунки.registries?.[источник.registry];
  if (!реестр) return null;
  if (плейсхолдер(источник.project) || плейсхолдер(средство.version)) return null;
  const база = (process.env.TRIP_TOOLS_REGISTRY_BASE || реестр.base_url).replace(/\/+$/, '');
  const проект = encodeURIComponent(источник.project);
  return {
    адрес: `${база}/api/v4/projects/${проект}/packages` +
      `?package_name=${encodeURIComponent(источник.package)}&per_page=100`,
    реестр,
  };
}

async function опубликованная(ходунки, средство) {
  const план = адресПакетов(ходунки, средство);
  if (!план) return { неприменимо: true };
  let заголовки;
  try {
    заголовки = заголовкиДоступа(план.реестр);
  } catch (ошибка) {
    return { ошибка: ошибка.message };
  }
  try {
    // Предел ожидания обязателен: у fetch его нет, а сверка версий — удобство,
    // которое не вправе подвешивать ни установку, ни гейт. Недоступный реестр
    // честнее назвать недоступным, чем ждать его до бесконечности.
    const ответ = await fetch(план.адрес, {
      headers: заголовки,
      redirect: 'follow',
      signal: AbortSignal.timeout(Number(process.env.TRIP_TOOLS_TIMEOUT_MS) || 10000),
    });
    if (!ответ.ok) return { ошибка: `${ответ.status} ${ответ.statusText}` };
    const список = await ответ.json();
    const имя = средство.source.package;
    const версии = (Array.isArray(список) ? список : [])
      .filter((пакет) => пакет?.name === имя && пакет?.version)
      .map((пакет) => String(пакет.version));
    if (!версии.length) return { ошибка: 'в реестре нет ни одного выпуска пакета' };
    return { версия: версии.sort(сравнитьВерсии).at(-1) };
  } catch (ошибка) {
    return { ошибка: ошибка.message };
  }
}

async function сверитьСРеестром(ходунки) {
  // Запросы идут разом: средств больше десяти, и последовательный обход
  // превратил бы сверку в десять задержек сети подряд — цену, за которую
  // удобство перестают включать.
  const отобрано = ходунки.tools.filter(
    (средство) => !отобранные.length || отобранные.includes(средство.id),
  );
  const итоги = await Promise.all(отобрано.map((средство) => опубликованная(ходунки, средство)));
  return итоги
    .map((итог, и) => ({ средство: отобрано[и], закреплено: отобрано[и].version, ...итог }))
    .filter((строка) => !строка.неприменимо);
}

/**
 * Отставание ходунков от реестра. Считается закрепление против опубликованного, а
 * не установленное против опубликованного: установленное отстаёт от ходунков по
 * другой причине и лечится одной строкой, без шаблона.
 */
async function печатьОтставания(ходунки) {
  if (безСети) {
    console.log('');
    console.log('Сверка с реестром пропущена: ключ --без-сети. Отставание ходунков неизвестно.');
    return 0;
  }
  const сверка = await сверитьСРеестром(ходунки);
  if (!сверка.length) return 0;
  const отставшие = сверка.filter((с) => с.версия && сравнитьВерсии(с.закреплено, с.версия) < 0);
  const неизвестные = сверка.filter((с) => с.ошибка);

  if (неизвестные.length) {
    // Причина у всех средств обычно одна — не задан токен, — и повторять её
    // строкой на средство значит спрятать её же в шуме.
    const группы = new Map();
    for (const с of неизвестные) {
      группы.set(с.ошибка, [...(группы.get(с.ошибка) ?? []), с.средство.id]);
    }
    console.log('');
    console.log(`Опубликованное неизвестно — реестр не ответил (средств ${неизвестные.length}):`);
    for (const [причина, средства] of группы) {
      console.log(`  ${причина}`);
      if (группы.size > 1) console.log(`    затронуты: ${средства.join(', ')}`);
    }
    console.log('Это не «актуально»: сверить версии было нечем.');
  }
  if (!отставшие.length) {
    if (!неизвестные.length) {
      console.log('');
      console.log('Ходунки совпадают с реестром пакетов.');
    }
    return 0;
  }

  console.log('');
  for (const с of отставшие) {
    const установлено = версияВПроекте(ходунки, с.средство) ?? 'нет';
    console.log(
      `${с.средство.id}: установлено ${установлено} — закреплено ${с.закреплено} — ` +
      `опубликовано ${с.версия}`,
    );
  }
  console.log('');
  console.log(`Проект отстал от реестра: средств ${отставшие.length}. Закрепление двигает шаблон,`);
  console.log('а не эта команда: сначала перенесите закрепление, потом доставьте выпуски.');
  console.log('');
  console.log('  node ИНСТРУМЕНТЫ/скрипты/обновить-оснастку.mjs');
  console.log('  node ИНСТРУМЕНТЫ/скрипты/инструменты.mjs установить');
  console.log('');
  console.log('Поднять version в ИНСТРУМЕНТЫ/training-wheels.json руками тоже можно, но тогда');
  console.log('отпечатки SHA-256 придётся вписать из реестра самому: без них установщик');
  console.log('откажет. Обычный порядок — через шаблон: он несёт и версию, и отпечатки.');
  return отставшие.length;
}

/** Версия средства, распакованного под проект; null — не установлено или молчит. */
function версияВПроекте(ходунки, средство) {
  const вход = средство.already_installed_check?.split(/\s+/) ?? [];
  if (!вход.length) return null;
  const каталог = join(КОРЕНЬ, ходунки.install_root, средство.id);
  if (!existsSync(каталог)) return null;
  for (const имя of [вход[0], `${вход[0]}.exe`]) {
    const путь = join(каталог, имя);
    if (!existsSync(путь)) continue;
    try {
      const вывод = execFileSync(путь, вход.slice(1), { encoding: 'utf8', timeout: 10000 });
      return вывод.trim().split(/\s+/).at(-1) ?? null;
    } catch {
      return null;
    }
  }
  return null;
}

/**
 * Посторонний вход в PATH. Короткое имя средства может звать не тот файл,
 * который закрепил проект, — и тогда `--version` показывает версию, к проекту
 * отношения не имеющую. Молчать об этом дороже всего: участник смотрит на
 * число и считает, что установка не сработала.
 */
function предупредитьОПостороннем(ходунки) {
  const свой = resolve(КОРЕНЬ, ходунки.install_root);
  for (const средство of ходунки.tools) {
    const вход = средство.already_installed_check?.split(/\s+/)?.[0];
    if (!вход) continue;
    if (!existsSync(join(свой, средство.id))) continue;
    let найденный;
    try {
      const поиск = process.platform === 'win32' ? ['where.exe', [вход]] : ['which', ['-a', вход]];
      найденный = execFileSync(поиск[0], поиск[1], { encoding: 'utf8', timeout: 10000 })
        .split(/\r?\n/)
        .map((с) => с.trim())
        .filter(Boolean)[0];
    } catch {
      continue;
    }
    if (!найденный || resolve(найденный).startsWith(свой)) continue;
    console.log('');
    console.log(`Внимание: в PATH найден другой ${вход} — ${найденный}.`);
    console.log(`Проект работает файлом из ${join(ходунки.install_root, средство.id)}.`);
    console.log(`Короткое «${вход}» зовёт первый, и его версия к проекту отношения не имеет.`);
  }
}

function строкаСостояния(средство, наличие, итог, вПроекте) {
  // Распакованное под проект — тоже установленное, и увидеть его нужно раньше
  // системного: именно его найдёт единый вход и именно его версию закрепил
  // проект. Иначе скрипт называет «нет» то, что лежит в двух шагах от него.
  if (вПроекте) return 'установлено: в проекте';
  if (наличие === true) return 'установлено: в системе';
  if (итог.ошибка) return `нет: ${итог.ошибка}`;
  return 'нет: доступно к загрузке';
}

async function проверить(ходунки) {
  const строки = [];
  let нехватка = 0;
  for (const средство of ходунки.tools) {
    const вПроекте = ужеВПроекте(ходунки, средство);
    const наличие = вПроекте ? true : уженВСистеме(средство);
    const план = адресВыпуска(ходунки, средство);
    const состояние = строкаСостояния(средство, наличие, план, вПроекте);
    if (средство.requirement === 'обязательное' && наличие !== true) нехватка += 1;
    строки.push([средство.id, средство.requirement, `Gate ${средство.needed_from_gate}`, состояние]);
  }
  const ширина = [0, 1, 2, 3].map((i) => Math.max(...строки.map((с) => с[i].length)));
  for (const с of строки) {
    console.log(с.map((з, i) => з.padEnd(ширина[i])).join('  '));
  }
  console.log('');
  if (нехватка === 0) {
    // Строка говорит только о наличии и раньше стояла последней: «на месте»
    // читалось как «всё в порядке», хотя на месте могло лежать устаревшее.
    console.log('Обязательные средства на месте.');
  } else {
    console.log(`Обязательных средств не хватает: ${нехватка}.`);
    console.log('Порядок получения — ИНСТРУМЕНТЫ/README.md.');
  }
  const отставание = await печатьОтставания(ходунки);
  предупредитьОПостороннем(ходунки);
  if (нехватка === 0 && отставание === 0) return 0;
  return строго ? 1 : 0;
}

