function сравнитьВерсии(а, б) {
  const разбор = (в) => String(в).split('.').map((ч) => Number.parseInt(ч, 10) || 0);
  const [а1, а2, а3] = разбор(а);
  const [б1, б2, б3] = разбор(б);
  return а1 - б1 || а2 - б2 || а3 - б3;
}

