test('отпечаток объявлен на каждый файл выпуска', () => {
  // Файлов у средства несколько — по одному на платформу. Отпечаток одной
  // строкой прикрывал бы ровно один из них, а остальные скачивались бы без
  // сверки; карта по тем же ключам закрывает каждый файл.
  const ходунки = JSON.parse(readFileSync(join(КОРЕНЬ, 'ИНСТРУМЕНТЫ', 'training-wheels.json'), 'utf8'));
  for (const средство of ходунки.tools) {
    if (средство.source?.kind !== 'generic-package') continue;
    assert.equal(typeof средство.sha256, 'object', `${средство.id}: sha256 должен быть картой по платформам`);
    for (const ключ of Object.keys(средство.source.files ?? {})) {
      assert.ok(
        typeof средство.sha256[ключ] === 'string' && средство.sha256[ключ].length > 0,
        `${средство.id}: для файла «${ключ}» не объявлен отпечаток`,
      );
    }
  }
});

// Порция навыков подключается в Gate 2, поэтому проверки работают на своей
// маленькой порции: они проверяют порядок установки, а не наличие поставки.
const КАТАЛОГ_НАВЫКОВ = join(КОРЕНЬ, '.agents', 'skills');

const навык = (имя, вид, версия = '1.0.0') => [
  '---',
  `name: ${имя}`,
  `description: Применять в проверке порядка установки навыка ${имя}. Второе предложение.`,
  'metadata:',
  `  version: "${версия}"`,
  `  trip-kind: ${вид}`,
  '  trip-maturity: "сделано"',
  '---',
  '',
  `# Навык ${имя}`,
  '',
].join('\n');

function собратьПорцию() {
  const порция = mkdtempSync(join(tmpdir(), 'trip-порция-'));
  mkdirSync(join(порция, 'trip-select-mode'), { recursive: true });
  writeFileSync(join(порция, 'trip-select-mode', 'SKILL.md'), навык('trip-select-mode', 'operational'), 'utf8');
  // Имя каталога-источника у практики намеренно не совпадает с полем name.
  mkdirSync(join(порция, 'ИНЖЕНЕРНЫЕ_ПРАКТИКИ', 'engineering-language'), { recursive: true });
  writeFileSync(
    join(порция, 'ИНЖЕНЕРНЫЕ_ПРАКТИКИ', 'engineering-language', 'SKILL.md'),
    навык('trip-practice-engineering-language', 'engineering-practice'),
    'utf8',
  );
  writeFileSync(join(порция, 'ИНЖЕНЕРНЫЕ_ПРАКТИКИ', 'LICENSE.md'), 'Apache-2.0\n', 'utf8');
  writeFileSync(join(порция, 'ИНЖЕНЕРНЫЕ_ПРАКТИКИ', 'NOTICE.md'), 'Уведомление\n', 'utf8');
  return порция;
}

function очиститьУстановку() {
  for (const запись of readdirSync(КАТАЛОГ_НАВЫКОВ)) {
    if (запись !== 'README.md') rmSync(join(КАТАЛОГ_НАВЫКОВ, запись), { recursive: true, force: true });
  }
}

function наПорции(проверка) {
  const порция = собратьПорцию();
  try {
    проверка(порция, запустить('навыки.mjs', ['установить-из', порция]));
  } finally {
    очиститьУстановку();
    rmSync(порция, { recursive: true, force: true });
  }
}

