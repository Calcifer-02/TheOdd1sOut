/*
 * Перечень инструкций называет версию, под которую снята копия, и ведётся
 * рукой. Пять строк из десяти отстали от ходунков — на выпуск, а trip-cast на
 * два. Читатель верит колонке «Версия», и неверная колонка хуже отсутствующей:
 * по ней сверяют, ту ли инструкцию читают.
 */
test('перечень инструкций называет те же версии, что и ходунки', () => {
  const ходунки = JSON.parse(readFileSync(join(КОРЕНЬ, 'ИНСТРУМЕНТЫ', 'training-wheels.json'), 'utf8'));
  const версии = new Map(ходунки.tools.map((с) => [с.id, с.version]));
  const перечень = readFileSync(join(КОРЕНЬ, 'ИНСТРУМЕНТЫ', 'ИНСТРУКЦИИ', 'README.md'), 'utf8');
  const строки = [...перечень.matchAll(/^\| (trip-[a-z-]+|tripwire)(?: \([^)]*\))? \| ([0-9][0-9.]*) \|/gmu)];
  assert.ok(строки.length >= 8, 'таблица состава не разобралась — проверка перестала что-либо проверять');
  for (const [, средство, названо] of строки) {
    const закреплено = версии.get(средство);
    assert.ok(закреплено, `перечень называет ${средство}, которого нет в ходунках`);
    assert.equal(названо, закреплено, `${средство}: перечень отстал от ходунков`);
  }
});
