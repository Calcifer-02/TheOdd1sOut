test('таблица средств в скрипте обновления совпадает с ходунками', () => {
  // Скрипт везёт версии в проекты, а ходунки — источник истины шаблона.
  // Расхождение означало бы, что проектам поехала не та версия, и заметить это
  // было бы некому: проект о новом выпуске узнаёт только из скрипта.
  const исходник = readFileSync(join(СКРИПТЫ, 'обновить-оснастку.mjs'), 'utf8');
  const ходунки = JSON.parse(readFileSync(join(КОРЕНЬ, 'ИНСТРУМЕНТЫ', 'training-wheels.json'), 'utf8'));
  const плейсхолдер = (з) => typeof з === 'string' && з.trim().startsWith('<');

  for (const средство of ходунки.tools) {
    const отпечатки = Object.entries(средство.sha256 ?? {}).filter(([, з]) => !плейсхолдер(з));
    if (плейсхолдер(средство.version) || отпечатки.length === 0) continue;

    const начало = исходник.indexOf(`'${средство.id}': {`);
    assert.ok(начало >= 0, `средство ${средство.id} не объявлено в таблице скрипта — его версия никуда не поедет`);
    const конец = исходник.indexOf('\n  },', начало);
    const блок = исходник.slice(начало, конец);
    const версия = блок.match(/версия: '([^']+)'/)?.[1];

    assert.equal(версия, средство.version, `версия ${средство.id} в скрипте разошлась с ходунками`);
    for (const [платформа, отпечаток] of отпечатки) {
      assert.ok(
        блок.includes(отпечаток),
        `отпечаток ${средство.id}/${платформа} в скрипте не совпадает с ходунками`,
      );
    }
  }
});

