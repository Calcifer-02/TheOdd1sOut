test('в шаблоне не осталось ссылок на прежние имена файлов', () => {
  // Переименовать файл и не переписать ссылку — хуже, чем не переименовать: в
  // проекте ходунки исчезали из-под установщика, и конвейер падал с «Ходунки
  // средств не найдены» уже после слияния. В шаблоне такое расхождение не должно быть
  // возможно вовсе, поэтому оно проверяется, а не подразумевается.
  const скрипт = readFileSync(join(СКРИПТЫ, 'обновить-оснастку.mjs'), 'utf8');
  const таблица = скрипт.match(/const ПЕРЕИМЕНОВАНИЯ = \[([\s\S]*?)\];/)?.[1];
  assert.ok(таблица, 'таблица переименований не найдена');
  const прежние = [...таблица.matchAll(/'([^']+)',\s*'[^']+'/g)].map((м) => м[1]);
  assert.ok(прежние.length > 0, 'таблица переименований пуста');

  const кандидаты = [];
  const обойти = (каталог) => {
    for (const запись of readdirSync(join(КОРЕНЬ, каталог), { withFileTypes: true })) {
      const путь = `${каталог}/${запись.name}`;
      if (запись.isDirectory()) {
        if (!['node_modules', '.git', 'ИНСТРУКЦИИ'].includes(запись.name)) обойти(путь);
      } else if (/\.(yml|yaml|mjs|js|md|sh|json)$/.test(запись.name)) {
        кандидаты.push(путь);
      }
    }
  };
  обойти('.gitlab');
  обойти('ИНСТРУМЕНТЫ');
  кандидаты.push('.gitlab-ci.yml', '.gitignore');
  for (const запись of readdirSync(КОРЕНЬ, { withFileTypes: true })) {
    if (запись.isFile() && запись.name.endsWith('.md')) кандидаты.push(запись.name);
  }

  for (const путь of кандидаты) {
    if (путь.endsWith('обновить-оснастку.mjs')) continue; // в нём и живёт таблица
    if (путь.endsWith('проверки.test.mjs')) continue; // и её разбор
    const текст = readFileSync(join(КОРЕНЬ, путь), 'utf8');
    for (const прежнее of прежние) {
      // Проверяются обе формы: полный путь и одно имя файла. Скрипты собирают
      // путь из частей, и расхождение прячется именно в короткой форме.
      for (const форма of [прежнее, прежнее.split('/').pop()]) {
        assert.ok(
          !текст.includes(форма),
          `${путь} ссылается на прежнее имя ${форма} — переименование не доведено`,
        );
      }
    }
  }
});

