// Самопроверка средств шаблона.
//
// Проверки фальсифицируемые: они падают, если проверка скелета перестанет
// находить незаменённые плейсхолдеры и битые ссылки, проверка навыков —
// расхождение отпечатка и реестра, а сборщик адресов — собирать адрес выпуска.
// Без этого гейты тихо превратятся в зелёные пустышки.
//
//   node --test ИНСТРУМЕНТЫ/скрипты/проверки.test.mjs

import { test } from 'node:test';
import assert from 'node:assert/strict';
import { createServer } from 'node:http';
import { execFile, execFileSync } from 'node:child_process';
import { promisify } from 'node:util';
import { readFileSync, writeFileSync, rmSync, mkdirSync, mkdtempSync, readdirSync, existsSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { basename, dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const СКРИПТЫ = dirname(fileURLToPath(import.meta.url));
const КОРЕНЬ = resolve(СКРИПТЫ, '..', '..');

function запустить(скрипт, аргументы = [], окружение = {}) {
  try {
    const вывод = execFileSync(process.execPath, [join(СКРИПТЫ, скрипт), ...аргументы], {
      cwd: КОРЕНЬ,
      encoding: 'utf8',
      env: { ...process.env, ...окружение },
    });
    return { код: 0, вывод };
  } catch (ошибка) {
    return { код: ошибка.status ?? 1, вывод: `${ошибка.stdout ?? ''}${ошибка.stderr ?? ''}` };
  }
}

// Проверки написаны для шаблона, но уезжают в проект, где плейсхолдеры уже
// заменены. Поэтому утверждение двустороннее: незаполненный шаблон обязан
// давать находку и падать под ключом строгости, заполненный — не давать и не
// падать. Односторонняя проверка краснела бы у каждой команды, которая честно
// сделала работу первого дня, и её быстро научились бы не читать.
test('незаменённый плейсхолдер находится, заменённый — нет', () => {
  const итог = запустить('проверить-скелет.mjs');
  const незаполнен = readFileSync(join(КОРЕНЬ, 'README.md'), 'utf8').includes('<Имя проекта>');
  if (незаполнен) assert.match(итог.вывод, /плейсхолдер <Имя проекта> не заменён: README\.md/);
  else assert.doesNotMatch(итог.вывод, /плейсхолдер <Имя проекта> не заменён/);
});

test('находки роняют проверку только под ключом строгости', () => {
  const мягко = запустить('проверить-скелет.mjs');
  assert.equal(мягко.код, 0);
  const естьНаходки = /находка:/.test(мягко.вывод);
  assert.equal(запустить('проверить-скелет.mjs', ['--строго']).код, естьНаходки ? 1 : 0);
});

test('в шаблоне нет битых относительных ссылок', () => {
  const итог = запустить('проверить-скелет.mjs');
  assert.doesNotMatch(итог.вывод, /битая ссылка/);
});

