/*
 * Один факт живёт в двух местах — значит, разойдётся. Скрипт обновления
 * оснастки носит в себе копию гейта следа и версию trip-cli, потому что ставит
 * их в проект, где файлов ещё нет. Копия обязана совпадать с источником, и
 * проверка ловит расхождение до того, как обновление вернёт проекту гейт,
 * который не запускается: так уже случилось — копия отстала на три исправления
 * образа сборки.
 */

function встроенное(имя) {
  const исходник = readFileSync(join(СКРИПТЫ, 'обновить-оснастку.mjs'), 'utf8');
  const начало = исходник.indexOf('const ' + имя + ' = `');
  assert.notEqual(начало, -1, 'константа ' + имя + ' не найдена в скрипте обновления');
  const открыто = исходник.indexOf('`', начало) + 1;
  const закрыто = исходник.indexOf('`;', открыто);
  return исходник
    .slice(открыто, закрыто)
    .replaceAll('\\`', '`')
    .replaceAll('\\${', '${')
    .replaceAll('\\\\', '\\');
}

