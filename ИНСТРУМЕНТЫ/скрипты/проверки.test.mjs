/*
 * Сверка ходунков с реестром. Проверки трёхсторонние намеренно: односторонняя
 * («отставание называется») пропустила бы два обратных отказа, каждый из
 * которых и есть то заблуждение, ради которого сверка заведена, — выдать
 * устаревшее за актуальное и выдать недоступный реестр за совпадение.
 *
 * Реестр подменяется заглушкой через TRIP_TOOLS_REGISTRY_BASE: обращаться к
 * настоящему в самопроверке нельзя — она обязана идти без токена и без сети.
 */
function сЗаглушкойРеестра(ответ, дело) {
  const сервер = createServer((запрос, отклик) => {
    if (typeof ответ === 'number') {
      отклик.writeHead(ответ, { 'Content-Type': 'application/json' });
      отклик.end('[]');
      return;
    }
    отклик.writeHead(200, { 'Content-Type': 'application/json' });
    отклик.end(JSON.stringify(ответ));
  });
  сервер.listen(0, '127.0.0.1');
  return new Promise((исполнить, отвергнуть) => {
    сервер.on('listening', async () => {
      const порт = сервер.address().port;
      try {
        исполнить(await дело(`http://127.0.0.1:${порт}`));
      } catch (ошибка) {
        отвергнуть(ошибка);
      } finally {
        сервер.close();
      }
    });
  });
}

function закреплённая(средство) {
  const ходунки = JSON.parse(readFileSync(join(КОРЕНЬ, 'ИНСТРУМЕНТЫ', 'training-wheels.json'), 'utf8'));
  const найдено = ходунки.tools.find((с) => с.id === средство);
  return { версия: найдено.version, пакет: найдено.source.package };
}

/*
 * Запуск именно асинхронный. execFileSync держит поток, и заглушка реестра,
 * живущая в этом же процессе, не успевает ответить дочернему: тест ждал бы
 * предел ожидания и проверял бы «реестр недоступен» вместо сверки.
 */
async function прогонСверки(база) {
  const выполнить = promisify(execFile);
  const окружение = {
    ...process.env,
    TRIP_TOOLS_REGISTRY_BASE: база,
    TRIP_TOOLS_TOKEN: 'stub-token',
    TRIP_TOOLS_TOKEN_KIND: 'deploy',
  };
  const аргументы = [join(СКРИПТЫ, 'инструменты.mjs'), 'проверить', 'trip-cli'];
  try {
    const { stdout, stderr } = await выполнить(process.execPath, аргументы, {
      cwd: КОРЕНЬ,
      encoding: 'utf8',
      env: окружение,
    });
    return { код: 0, вывод: `${stdout}${stderr}` };
  } catch (ошибка) {
    return { код: ошибка.code ?? 1, вывод: `${ошибка.stdout ?? ''}${ошибка.stderr ?? ''}` };
  }
}

test('отставание ходунков от реестра называется вместе с порядком подъёма', async () => {
  const { пакет } = закреплённая('trip-cli');
  const итог = await сЗаглушкойРеестра(
    [{ name: пакет, version: '999.0.0' }],
    (база) => прогонСверки(база),
  );
  assert.match(итог.вывод, /Проект отстал от реестра/u);
  assert.match(итог.вывод, /опубликовано 999\.0\.0/u);
  assert.match(итог.вывод, /обновить-оснастку\.mjs/u);
  assert.match(итог.вывод, /инструменты\.mjs установить/u);
});

