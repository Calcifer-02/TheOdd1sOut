test('адрес выпуска собирается по замку версий', () => {
  // Версия берётся из ходунков, а не переписывается в ожидание при каждом подъёме:
  // зашитый номер ронял бы проверку на любой смене выпуска, и чинили бы её
  // правкой ожидания. Утверждение при этом не ослабло — адрес обязан нести
  // именно ту версию, которую закрепили ходунки.
  const ходунки = JSON.parse(readFileSync(join(КОРЕНЬ, 'ИНСТРУМЕНТЫ', 'training-wheels.json'), 'utf8'));
  const версия = ходунки.tools.find((с) => с.id === 'trip-doc-lint').version;
  const итог = запустить('инструменты.mjs', ['план']);
  assert.match(итог.вывод, new RegExp(`packages/generic/trip-doc-lint/${версия.replace(/\./g, '\\.')}/`));
  assert.match(итог.вывод, /TRIP%2Ftooling%2Ftrip-doc-lint/);
});

