#!/usr/bin/env node
// Проверка скелета репозитория: зоны на месте, плейсхолдеры заменены,
// относительные ссылки в документах ведут в существующие файлы, а описание
// конвейера читается YAML так, как написано.
//
// Проверка не требует ни одного внешнего средства и работает в любом
// окружении с Node. Это нижний рубеж: он ловит незаполненный шаблон,
// а не качество содержания.
//
//   node ИНСТРУМЕНТЫ/скрипты/проверить-скелет.mjs
//   node ИНСТРУМЕНТЫ/скрипты/проверить-скелет.mjs --строго
//
// Три уровня. Заметка — состояние, а не долг. Находка — незаполненный шаблон:
// печатается всегда, роняет проверку только под ключом --строго, потому что
// пока команда приводит шаблон к проекту, падение сборки мешает; ключ включается
// в гейт, когда шаблон объявлен приведённым. Поломка роняет проверку всегда:
// нечитаемое описание конвейера промежуточным состоянием не бывает.

import { readFileSync, readdirSync, existsSync, statSync } from 'node:fs';
import { dirname, join, resolve, relative, posix } from 'node:path';
import { fileURLToPath } from 'node:url';

const КОРЕНЬ = resolve(dirname(fileURLToPath(import.meta.url)), '..', '..');
const строго = process.argv.includes('--строго');

const ЗОНЫ = [
  { путь: 'README.md', вид: 'файл', важность: 'обязательная', имя: 'Корневое описание' },
  { путь: '.gitignore', вид: 'файл', важность: 'обязательная', имя: 'Правила исключений' },
  { путь: 'trip.json', вид: 'файл', важность: 'обязательная', имя: 'Описание политик trip' },
  { путь: 'trip', вид: 'каталог', важность: 'обязательная', имя: 'Валидаторы политик trip' },
  { путь: 'docs', вид: 'каталог', важность: 'обязательная', имя: 'Аналитика' },
  { путь: 'МЕТОДОЛОГИЯ', вид: 'каталог', важность: 'рекомендуемая', имя: 'Выданная порция методологии' },
  { путь: '.agents/skills', вид: 'каталог', важность: 'рекомендуемая', имя: 'Навыки агента' },
  { путь: 'src', вид: 'каталог', важность: 'рекомендуемая', имя: 'Исходный код' },
  { путь: 'tests', вид: 'каталог', важность: 'рекомендуемая', имя: 'Проверки' },
  { путь: 'devops', вид: 'каталог', важность: 'рекомендуемая', имя: 'Запуск и эксплуатация' },
  { путь: 'ux', вид: 'каталог', важность: 'рекомендуемая', имя: 'Материалы интерфейса' },
  { путь: 'client', вид: 'каталог', важность: 'рекомендуемая', имя: 'Материалы заказчика' },
  { путь: 'LICENSE', вид: 'файл', важность: 'рекомендуемая', имя: 'Условия использования' },
];

// Плейсхолдеры, которые обязаны исчезнуть до первого содержательного коммита.
const ОБЯЗАТЕЛЬНЫЕ_ЗАМЕНЫ = [
  { файл: 'README.md', образец: '<Имя проекта>' },
  { файл: 'AGENTS.md', образец: '<Имя проекта>' },
  { файл: 'CLAUDE.md', образец: '<Имя проекта>' },
  { файл: 'trip.json', образец: '<Имя проекта>' },
  { файл: '.trip/HARNESS_PROFILE.yaml', образец: '<идентификатор-проекта>' },
];

// Описание конвейера разбирается здесь, а не заданием самого конвейера:
// пайплайн с нечитаемым описанием GitLab не создаёт вовсе, поэтому ни одно
// задание — включая гейт скелета — не запускается. Единственное место, где
// такую поломку ещё можно поймать, — машина автора до отправки.
const ИСТОЧНИКИ_КОНВЕЙЕРА = ['.gitlab-ci.yml', '.gitlab/ci'];
const КЛЮЧИ_КОМАНД = 'script|before_script|after_script';

// Имя переменной GitLab подставляет по правилу оболочки: латиница, цифры и
// подчёркивание. Кириллическое имя описание не отвергает — подстановки просто
// не происходит, и «image: $ОБРАЗ_NODE» уезжает в docker буквально. Раннер
// отвечает «invalid reference format», а сборка показывает это отказом раннера,
// а не опечаткой в описании: искать причину идут не туда.
const ССЫЛКА_НА_ПЕРЕМЕННУЮ = /\$\{?([\p{L}\p{N}_]+)/gu;
const ВНЕ_ЛАТИНИЦЫ = /[^\x00-\x7F]/;

const ПРОПУСК = new Set(['node_modules', '.git', 'установленное', 'dist', 'build']);

// Ссылки на ещё не существующие цели с известным основанием. Список закрытый:
// он объясняет каждое исключение, а не глушит проверку целиком.
const ИЗВЕСТНЫЕ_ИСКЛЮЧЕНИЯ = [
  {
    источник: 'AGENTS.md',
    цель: './СОСТОЯНИЕ_ПРОЕКТА.md',
    основание: 'состояние проекта генерируется средствами и не заводится руками',
  },
];

const поломки = [];
const находки = [];
const заметки = [];

function обойти(каталог, накопитель = []) {
  for (const запись of readdirSync(каталог, { withFileTypes: true })) {
    if (ПРОПУСК.has(запись.name)) continue;
    const полный = join(каталог, запись.name);
    if (запись.isDirectory()) обойти(полный, накопитель);
    else if (запись.name.endsWith('.md')) накопитель.push(полный);
  }
  return накопитель;
}

function проверитьЗоны() {
  for (const зона of ЗОНЫ) {
    const полный = join(КОРЕНЬ, зона.путь);
    const есть = existsSync(полный) &&
      (зона.вид === 'каталог' ? statSync(полный).isDirectory() : statSync(полный).isFile());
    if (есть) continue;
    const запись = `зона «${зона.имя}» отсутствует: ${зона.путь}`;
    if (зона.важность === 'обязательная') находки.push(запись);
    else заметки.push(запись);
  }
}

function проверитьЗамены() {
  for (const замена of ОБЯЗАТЕЛЬНЫЕ_ЗАМЕНЫ) {
    const полный = join(КОРЕНЬ, замена.файл);
    if (!existsSync(полный)) {
      находки.push(`файл не найден: ${замена.файл}`);
      continue;
    }
    if (readFileSync(полный, 'utf8').includes(замена.образец)) {
      находки.push(`плейсхолдер ${замена.образец} не заменён: ${замена.файл}`);
    }
  }
  for (const остаток of ['ПЕРВЫЕ_ШАГИ.md', 'ДЛЯ_АДМИНИСТРАТОРА']) {
    if (existsSync(join(КОРЕНЬ, остаток))) {
      заметки.push(`материал шаблона ещё в репозитории и удаляется после первого дня: ${остаток}`);
    }
  }
}

// Разметка внутри кода — не ссылка, а пример записи: её цель существовать не
// обязана. Разбор кода наравне с текстом давал бы находки на образцах из
// инструкций к средствам и прятал бы за ними настоящие битые ссылки.
function безКода(текст) {
  let вКоде = false;
  return текст
    .split('\n')
    .map((строка) => {
      if (/^\s*(```|~~~)/.test(строка)) {
        вКоде = !вКоде;
        return '';
      }
      return вКоде ? '' : строка.replace(/`[^`]*`/g, '');
    })
    .join('\n');
}

function проверитьСсылки() {
  const образец = /\[[^\]]*\]\(([^)\s]+)\)/g;
  for (const файл of обойти(КОРЕНЬ)) {
    const текст = безКода(readFileSync(файл, 'utf8'));
    for (const совпадение of текст.matchAll(образец)) {
      const цель = совпадение[1];
      if (/^(https?:|mailto:|#)/.test(цель)) continue;
      const безЯкоря = decodeURIComponent(цель.split('#')[0]);
      if (!безЯкоря) continue;
      const назначение = резолв(файл, безЯкоря);
      if (existsSync(назначение)) continue;
      const исключение = ИЗВЕСТНЫЕ_ИСКЛЮЧЕНИЯ.find(
        (и) => и.источник === отн(файл) && и.цель === цель,
      );
      if (исключение) {
        заметки.push(`ссылка ждёт цель: ${отн(файл)} -> ${цель} (${исключение.основание})`);
        continue;
      }
      находки.push(`битая ссылка: ${отн(файл)} -> ${цель}`);
    }
  }
}

function файлыКонвейера() {
  const собранные = [];
  for (const источник of ИСТОЧНИКИ_КОНВЕЙЕРА) {
    const полный = join(КОРЕНЬ, источник);
    if (!existsSync(полный)) continue;
    if (!statSync(полный).isDirectory()) {
      собранные.push(полный);
      continue;
    }
    for (const запись of readdirSync(полный).sort()) {
      if (/\.ya?ml$/.test(запись)) собранные.push(join(полный, запись));
    }
  }
  return собранные;
}

// Ловится один класс поломки — тот самый, что роняет пайплайн целиком: команда
// записана без кавычек и содержит двоеточие с пробелом. YAML читает такую
// строку как пару «ключ: значение», задание получает вместо команды словарь, и
// GitLab отвечает «script config should be a string or a nested array of
// strings» — ещё до того, как запустится хоть одно задание.
//
// Класс выбран за отсутствие догадок: незакавыченный скаляр с «: » — всегда
// отображение, другого прочтения у YAML для него нет. Полный разбор YAML
// потребовал бы зависимости, которой у скриптов шаблона нет.
function проверитьПеременные(файл, строки) {
  let объявления = null; // отступ ключа variables:; null — мы вне блока объявлений
  for (const [номер, строка] of строки.entries()) {
    const очищенная = строка.trim();
    if (!очищенная || очищенная.startsWith('#')) continue;
    const отступ = строка.search(/\S/);
    if (объявления !== null && отступ <= объявления) объявления = null;
    if (/^\s*variables:\s*$/.test(строка)) {
      объявления = отступ;
      continue;
    }
    if (объявления !== null) {
      const ключ = очищенная.match(/^([^:#]+):/);
      if (ключ && ВНЕ_ЛАТИНИЦЫ.test(ключ[1])) {
        поломки.push(
          `${отн(файл)}:${номер + 1}: имя переменной «${ключ[1].trim()}» вне латиницы — ` +
            'GitLab такое имя не подставляет, задание получит ссылку на него дословно',
        );
      }
    }
    for (const совпадение of строка.matchAll(ССЫЛКА_НА_ПЕРЕМЕННУЮ)) {
      if (!ВНЕ_ЛАТИНИЦЫ.test(совпадение[1])) continue;
      поломки.push(
        `${отн(файл)}:${номер + 1}: ссылка на переменную «$${совпадение[1]}» вне латиницы — ` +
          'подстановки не будет, значение уедет в задание дословно',
      );
    }
  }
}

function проверитьКонвейер() {
  const объявление = new RegExp(`^\\s*(?:${КЛЮЧИ_КОМАНД}):\\s*(\\S.*)?$`);
  for (const файл of файлыКонвейера()) {
    const строки = readFileSync(файл, 'utf8').split('\n');
    проверитьПеременные(файл, строки);
    let команды = null; // отступ ключа команд; null — мы вне списка команд
    let дословно = null; // отступ элемента «- |»; внутри блока строки не разбираются
    for (const [номер, строка] of строки.entries()) {
      if (!строка.trim()) continue;
      const отступ = строка.search(/\S/);
      if (дословно !== null) {
        if (отступ > дословно) continue;
        дословно = null;
      }
      if (команды !== null && отступ <= команды) команды = null;
      const начало = строка.match(объявление);
      if (начало) {
        команды = начало[1] ? null : отступ; // «script: команда» одной строкой списка не открывает
        continue;
      }
      if (команды === null) continue;
      const элемент = строка.match(/^\s*-\s+(.*)$/);
      if (!элемент) continue;
      const значение = элемент[1].trim();
      if (/^[|>]/.test(значение)) {
        дословно = отступ;
        continue;
      }
      if (/^['"]/.test(значение)) continue;
      if (!/:(\s|$)/.test(значение)) continue;
      поломки.push(
        `${отн(файл)}:${номер + 1}: команда конвейера содержит «: » без кавычек — ` +
          'YAML прочитает её как пару «ключ: значение», и пайплайн не создастся; ' +
          'возьмите строку целиком в одинарные кавычки',
      );
    }
  }
}

const резолв = (файл, цель) =>
  цель.startsWith('/') ? join(КОРЕНЬ, цель.slice(1)) : resolve(dirname(файл), цель);

const отн = (файл) => relative(КОРЕНЬ, файл).split('\\').join(posix.sep);

проверитьЗоны();
проверитьЗамены();
проверитьСсылки();
проверитьКонвейер();

for (const заметка of заметки) console.log(`заметка: ${заметка}`);
for (const находка of находки) console.log(`находка: ${находка}`);
for (const поломка of поломки) console.log(`поломка: ${поломка}`);

if (поломки.length === 0 && находки.length === 0) {
  console.log('Скелет репозитория в порядке.');
  process.exit(0);
}
console.log('');
if (поломки.length > 0) {
  console.log(`Поломок: ${поломки.length}. Сборка не запустится, пока они есть.`);
}
if (находки.length > 0) {
  console.log(`Находок: ${находки.length}. Порядок первого дня — ПЕРВЫЕ_ШАГИ.md.`);
}
process.exit(поломки.length > 0 || строго ? 1 : 0);
