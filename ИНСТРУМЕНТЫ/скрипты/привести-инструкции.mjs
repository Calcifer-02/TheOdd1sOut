#!/usr/bin/env node
// Приводит копии инструкций средств (ИНСТРУМЕНТЫ/ИНСТРУКЦИИ/) к автономному виду:
// относительные ссылки на файлы исходных репозиториев средств (у команды их нет)
// заменяются на текст с путём в код-формате. Внешние ссылки, якоря и живые
// локальные ссылки не трогаются. Запускать после обновления копий из выпусков.

import { readdirSync, readFileSync, writeFileSync, existsSync } from 'node:fs';
import { join, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';

const КОРЕНЬ = join(dirname(fileURLToPath(import.meta.url)), '..');
const ПАПКА = join(КОРЕНЬ, 'ИНСТРУКЦИИ');

function файлыMd(папка) {
  const выход = [];
  for (const запись of readdirSync(папка, { withFileTypes: true })) {
    const путь = join(папка, запись.name);
    if (запись.isDirectory()) выход.push(...файлыMd(путь));
    else if (запись.name.endsWith('.md')) выход.push(путь);
  }
  return выход;
}

// [текст](цель) и ![текст](цель) вне код-блоков; цель без пробелов, необязательный title опускаем
const ССЫЛКА = /(!?)\[([^\]]*)\]\(([^)\s]+)(?:\s+"[^"]*")?\)/g;

// Копии переименованы по-русски, а ссылки внутри них написаны на имена файлов
// исходного репозитория. Документ, который у команды есть под другим именем, —
// не повод отправлять читателя в репозиторий, доступа к которому у него нет.
// Список закрытый: он объясняет каждое переименование, а не угадывает их.
const ПЕРЕИМЕНОВАНИЯ = new Map([
  ['policies-model.md', 'МОДЕЛЬ_ПОЛИТИК.md'],
  ['user-guide.md', 'РУКОВОДСТВО_ПОЛЬЗОВАТЕЛЯ.md'],
]);

let всего = 0;
let переадресовано = 0;
for (const файл of файлыMd(ПАПКА)) {
  const строки = readFileSync(файл, 'utf8').split('\n');
  let вКоде = false;
  let замен = 0;
  const итог = строки.map((строка) => {
    if (строка.trimStart().startsWith('```')) { вКоде = !вКоде; return строка; }
    if (вКоде) return строка;
    return строка.replace(ССЫЛКА, (whole, img, текст, цель) => {
      if (/^(https?:|mailto:|#|\/)/.test(цель)) return whole;
      const путь = decodeURIComponent(цель.split('#')[0]);
      if (!путь) return whole; // чистый якорь
      if (existsSync(join(dirname(файл), путь))) return whole;
      // Раскладка исходного репозитория в копии не воспроизводится, поэтому
      // ищем по имени файла. Условие остаётся жёстким: переадресация возможна
      // только на файл, лежащий рядом с этим же документом, — в свою поставку,
      // а не в чужую.
      const переименованный = ПЕРЕИМЕНОВАНИЯ.get(путь.split('/').pop());
      if (переименованный && existsSync(join(dirname(файл), переименованный))) {
        const якорь = цель.includes('#') ? `#${цель.split('#').slice(1).join('#')}` : '';
        замен += 1;
        переадресовано += 1;
        return `${img}[${текст}](./${переименованный}${якорь})`;
      }
      замен += 1;
      const метка = текст || путь;
      return `\`${метка}\` (\`${цель}\` — в исходном репозитории средства)`;
    });
  });
  if (замен > 0) {
    writeFileSync(файл, итог.join('\n'));
    console.log(`${файл.slice(КОРЕНЬ.length + 1)}: правок ссылок: ${замен}`);
    всего += замен;
  }
}
console.log(
  всего === 0
    ? 'Битых ссылок на исходные репозитории нет.'
    : `Всего правок: ${всего}, из них переадресовано на копию рядом: ${переадресовано}.`,
);
