// Форматирование сумм, чисел, дат и объёмов по локали ru-RU (R-061).
// Деньги приходят от расчётной части строкой с двумя знаками после точки
// (схема `Money` договора), а вид числа — работа интерфейса: единственный
// форматтер, а не подсчёт в каждом компоненте (ADR-0008, «Договор как
// источник типов»).
//
// Проверки фальсифицируемы: замените неразрывный пробел на обычный, покажите
// нулевые копейки, поставьте десятичную точку вместо запятой, разберите дату
// через `new Date(...)` без учёта часового пояса или напишите «м3» вместо
// «м³» — они упадут.
import { describe, expect, it } from 'vitest';
import { formatDate, formatMoney, formatNumber, formatQuantity } from '../src/formatting';

/** Неразрывный пробел U+00A0 — единственный разделитель разрядов в ru-RU. */
const NBSP = ' ';

/** @ac: AC-061b */
describe('формат денежной суммы', () => {
  it('разделяет разряды и знак рубля неразрывным пробелом', () => {
    const shown = formatMoney({ amount: '19800.00', currency: 'RUB' });

    expect(shown).toBe(`19${NBSP}800${NBSP}₽`);
    expect(shown, 'обычный пробел рвёт строку и ломает выравнивание по разрядам').not.toContain(
      ' ',
    );
  });

  it('прячет копейки, когда они нулевые', () => {
    expect(formatMoney({ amount: '19800.00', currency: 'RUB' })).not.toContain(',');
  });

  it('показывает копейки, когда они не нулевые', () => {
    expect(formatMoney({ amount: '19800.50', currency: 'RUB' })).toBe(`19${NBSP}800,50${NBSP}₽`);
  });

  it('обходится без разделителя разрядов у суммы меньше тысячи', () => {
    expect(formatMoney({ amount: '900.00', currency: 'RUB' })).toBe(`900${NBSP}₽`);
  });

  it('показывает нулевую сумму числом, а не пустой строкой', () => {
    expect(formatMoney({ amount: '0.00', currency: 'RUB' })).toBe(`0${NBSP}₽`);
  });

  it('не показывает отрицательную сумму как обычную цену', () => {
    // Отрицательная сумма в смете — дефект данных. Знак теряться не должен:
    // «−19 800 ₽» видно, «19 800 ₽» вместо него — тихая ложь.
    const negative = formatMoney({ amount: '-19800.00', currency: 'RUB' });

    expect(negative).not.toBe(formatMoney({ amount: '19800.00', currency: 'RUB' }));
    expect(negative).toMatch(/^[-−]/u);
  });
});

/** @ac: AC-061b */
describe('формат числа', () => {
  it('отделяет дробную часть запятой', () => {
    expect(formatNumber(7.5)).toBe('7,5');
  });

  it('не приписывает целому числу нулевую дробную часть', () => {
    expect(formatNumber(20)).toBe('20');
  });

  it('показывает ноль числом', () => {
    expect(formatNumber(0)).toBe('0');
  });

  it('не показывает десятичную точку', () => {
    expect(formatNumber(0.5)).not.toContain('.');
  });
});

/** @ac: AC-048d, AC-061b */
describe('формат даты', () => {
  it('показывает дату днём, месяцем и годом через точку', () => {
    expect(formatDate('2026-09-17')).toBe('17.09.2026');
  });

  it('дополняет день и месяц нулём до двух знаков', () => {
    expect(formatDate('2026-01-05')).toBe('05.01.2026');
  });

  it('не сдвигает дату часовым поясом', () => {
    // `new Date('2026-01-01')` разбирается как полночь UTC: в поясе западнее
    // Гринвича наивный показ даёт 31.12.2025 (карточка практики PRACT-027).
    expect(formatDate('2026-01-01')).toBe('01.01.2026');
  });
});

/** @ac: AC-014b, AC-015c, AC-061b */
describe('формат объёма отходов', () => {
  it('ставит меру «т» после числа тонн', () => {
    expect(formatQuantity(20, 't')).toMatch(/^20[\s ]т$/u);
  });

  it('ставит меру «м³» после числа кубометров', () => {
    expect(formatQuantity(15, 'm3')).toMatch(/^15[\s ]м³$/u);
  });

  it('не записывает кубометры как «м3»', () => {
    expect(formatQuantity(15, 'm3')).not.toContain('м3');
  });

  it('отделяет дробную часть объёма запятой', () => {
    expect(formatQuantity(7.5, 't')).toMatch(/^7,5[\s ]т$/u);
  });

  it('показывает нулевой объём числом', () => {
    expect(formatQuantity(0, 't')).toMatch(/^0[\s ]т$/u);
  });
});
