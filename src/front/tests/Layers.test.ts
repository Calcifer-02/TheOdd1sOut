/**
 * Направление подключений между слоями интерфейса.
 *
 * Практика PRACT-012 требует, чтобы граница слоёв держалась средством, а не
 * договорённостью, — и чтобы вводилась она по наблюдаемой проблеме, а не по
 * названию раскладки. Проблема наблюдаемая: одна предметная часть обслуживает
 * два представления (десктопное и мобильное), а поверх неё встают ещё три
 * экрана. Без границы «общее» начнёт тянуться к «частному» и перестанет быть
 * общим.
 *
 * Правил два, оба проверяются статически. Слой подключается только к слоям
 * ниже себя. Чужой слайс подключается через его публичный вход, а не по
 * внутреннему пути.
 *
 * Проверка фальсифицируема: подключите в `shared` что-нибудь из `entities`
 * либо сошлитесь на `@/entities/landfill/ui/OptionCard` вместо
 * `@/entities/landfill` — она назовёт файл и строку.
 *
 *   npx vitest run tests/Layers.test.ts
 */
import { describe, expect, it } from 'vitest';
import { sourceFiles } from './repository';

/** Слои снизу вверх: общий слой ничего о вышестоящих не знает. */
const СЛОИ = ['shared', 'entities', 'features', 'widgets', 'pages', 'app'] as const;

type Слой = (typeof СЛОИ)[number];

const ПРЕФИКС = 'src/front/src/';

/** Слой, к которому принадлежит файл, и слайс внутри слоя. */
function место(path: string): { слой: Слой; слайс: string } | null {
  if (!path.startsWith(ПРЕФИКС)) {
    return null;
  }

  const части = path.slice(ПРЕФИКС.length).split('/');
  const слой = части[0] as Слой;

  return СЛОИ.includes(слой) ? { слой, слайс: части[1] ?? '' } : null;
}

/** Подключения вида `@/<слой>/<слайс>/…` из текста модуля. */
function подключения(text: string): { слой: Слой; слайс: string; путь: string }[] {
  return [...text.matchAll(/from '@\/([^']+)'/g)].flatMap(match => {
    const части = match[1].split('/');
    const слой = части[0] as Слой;

    return СЛОИ.includes(слой) ? [{ слой, слайс: части[1] ?? '', путь: match[1] }] : [];
  });
}

const модули = sourceFiles().filter(file => место(file.path) !== null);

describe('слои интерфейса', () => {
  it('содержит разложенные по слоям модули', () => {
    // Пустая выборка сделала бы обе проверки ниже бессодержательными: они
    // прошли бы просто потому, что проверять нечего.
    expect(модули.length).toBeGreaterThan(10);
  });

  it('подключается только к слоям ниже себя', () => {
    const нарушения = модули.flatMap(file => {
      const свой = место(file.path)!;

      return (
        подключения(file.text)
          .filter(ссылка => СЛОИ.indexOf(ссылка.слой) >= СЛОИ.indexOf(свой.слой))
          // Свой уровень допустим внутри общего слоя — он разложен на отрезки,
          // а не на слайсы, — и внутри своего же слайса.
          .filter(ссылка => !(свой.слой === 'shared' && ссылка.слой === 'shared'))
          .filter(ссылка => !(ссылка.слой === свой.слой && ссылка.слайс === свой.слайс))
          .map(ссылка => `${file.path}: ${свой.слой} → ${ссылка.путь}`)
      );
    });

    expect(нарушения, 'слой подключился к своему уровню или выше').toEqual([]);
  });

  it('подключается к чужому слайсу через его публичный вход', () => {
    // Общий слой исключён: его публичные входы объявлены по отрезкам
    // («@/shared/api/contracts»), а не по слайсам.
    const нарушения = модули.flatMap(file => {
      const свой = место(file.path)!;

      return подключения(file.text)
        .filter(ссылка => ссылка.слой !== 'shared')
        .filter(ссылка => ссылка.путь.split('/').length > 2)
        .filter(ссылка => !(ссылка.слой === свой.слой && ссылка.слайс === свой.слайс))
        .map(ссылка => `${file.path}: ${ссылка.путь}`);
    });

    expect(нарушения, 'подключение в обход публичного входа слайса').toEqual([]);
  });
});
