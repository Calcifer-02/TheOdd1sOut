/**
 * Адрес сервиса в сети и файлы, которые из него собираются.
 *
 * Адрес нужен разметке страницы (канонический адрес, предпросмотр ссылки),
 * карте сайта и правилам обхода. Написанный в каждом из этих мест своей рукой,
 * он расходится на первом же переезде: страница объявляет себя каноническим
 * одним адресом, карта сайта называет другой, и поисковая система выбирает
 * сама. Поэтому адрес объявлен здесь один раз, а разметка получает его
 * подстановкой при сборке.
 *
 * Смена домена — правка одной строки ниже: логики, зависящей от адреса, в
 * сервисе нет, обращения к расчётной части идут относительным путём «/api».
 *
 * @supports: R-058
 */

/** Адрес, по которому сервис отвечает. Без косой черты в конце. */
export const SITE_ORIGIN = 'https://triadmind.ru';

/**
 * Дата последнего значимого изменения страницы для карты сайта.
 *
 * Дата объявлена, а не взята у часов машины: сборка обязана быть
 * воспроизводимой, а «сегодня» в сборке делает каждый образ отличным от
 * предыдущего и заявляет обновление там, где ничего не менялось.
 */
export const SITE_UPDATED = '2026-09-24';

/**
 * Карта сайта.
 *
 * Адрес у сервиса ровно один: переходы между экранами живут в части адреса
 * после решётки, а её обходчик поисковой системы не различает — «/#/landfills»
 * для него тот же самый «/». Отдельные адреса экранов потребовали бы перевода
 * маршрутизации на путь и согласия платформы MAX, и это отдельное решение.
 */
export function sitemapXml(): string {
  return [
    '<?xml version="1.0" encoding="UTF-8"?>',
    '<urlset xmlns="http://www.sitemaps.org/schemas/sitemap/0.9">',
    '  <url>',
    `    <loc>${SITE_ORIGIN}/</loc>`,
    `    <lastmod>${SITE_UPDATED}</lastmod>`,
    '    <changefreq>weekly</changefreq>',
    '  </url>',
    '</urlset>',
    '',
  ].join('\n');
}

/** Правила обхода. Витрина компонентов — внутренний артефакт, а не страница. */
export function robotsTxt(): string {
  return [
    'User-agent: *',
    'Allow: /',
    '',
    '# Витрина компонентов — внутренний артефакт эстетики, а не страница сервиса.',
    'Disallow: /vitrina.html',
    '',
    `Sitemap: ${SITE_ORIGIN}/sitemap.xml`,
    '',
  ].join('\n');
}
