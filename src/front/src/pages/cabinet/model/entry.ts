/**
 * Что участник получает в разделе кабинета.
 *
 * @supports: R-049, R-050, R-052, R-085
 */
export type CabinetBenefit = {
  section: CabinetSection;
  detail: string;
};

/**
 * Перечень возможностей кабинета. Названы те три, о которых говорит
 * объяснение входа: сохранённые расчёты, подписка и заказ документации.
 * Разделы «Маршруты» и «Профиль» в перечень не вошли — маршрут открывается
 * из расчёта, а реквизиты профиля приходят из заявки на подписку, и обещать
 * их отдельной возможностью нечестно.
 *
 * @supports: R-049, R-050, R-052, R-085
 */
export const CABINET_BENEFITS: CabinetBenefit[] = [
  { section: 'calculations', detail: 'Сохранённые расчёты и выпущенные коммерческие предложения' },
  { section: 'subscription', detail: subscriptionExplanation('none') },
  {
    section: 'services',
    detail: 'Цена указана от минимального объёма работ – точную назовёт менеджер после уточнения объекта.',
  },
];

/**
 * Имя раздела. Берётся у навигации, а не объявляется рядом: перечень на входе
 * и боковое меню обязаны называть раздел одинаково.
 *
 * @supports: R-049, R-050, R-052, R-085
 */
export function benefitLabel(section: CabinetSection): string {
  return CABINET_SECTIONS.find(item => item.value === section)?.label ?? '';
}

/**
 * Пояснение раздела: оно же стоит подписью под заголовком самого раздела.
 *
 * @supports: R-049, R-050, R-052, R-085
 */
export function benefitDetail(section: CabinetSection): string {
  return CABINET_BENEFITS.find(item => item.section === section)?.detail ?? '';
}
