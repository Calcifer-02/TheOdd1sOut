/**
 * Стартовые параметры платформы MAX.
 *
 * Библиотека платформы подключается отдельным скриптом и объявляет глобальный
 * объект; пакета в реестре пакетов у неё нет. Отсюда два следствия, и оба
 * учтены здесь. Первое: объекта может не быть вовсе — приложение открыли по
 * прямой ссылке, или скрипт не загрузился. Второе: строка стартовых
 * параметров уходит на сервер как есть, без разбора, — проверить подпись
 * можно только по исходной строке (ADR-0006).
 *
 * Разобранный платформой объект здесь намеренно не читается: он не подписан,
 * и принимать по нему решения о личности нельзя.
 *
 * @shared: imolt-miniapp
 * @adr: ADR-0009
 */

declare global {
  interface Window {
    WebApp?: {
      initData?: string;
    };
  }
}

/**
 * Строка стартовых параметров или `null`, если приложение открыто не из
 * переписки. Отсутствие — рабочее состояние: главный путь расчёта проходится
 * без личности (ADR-0009).
 */
export function launchParameters(): string | null {
  const data = typeof window === 'undefined' ? undefined : window.WebApp?.initData;

  return typeof data === 'string' && data.length > 0 ? data : null;
}

/** Открыто ли приложение из переписки с чат-ботом. */
export function openedFromChat(): boolean {
  return launchParameters() !== null;
}
