/**
 * Иллюстрации карточек-объяснений: перевозка, маршрут по дорогам, дата
 * подтверждения данных.
 *
 * Карточка из одного заголовка и абзаца читается как незаконченная (BUG-006),
 * а эмодзи и объёмная картинка дизайн-договором запрещены (разд. 4.6).
 * Поэтому рисунок — встроенный контур: он берёт цвет у текста карточки,
 * остаётся чётким на любой плотности экрана и не тянет за собой файл.
 *
 * Рисунок сопровождает подпись, а не заменяет её: `aria-hidden` убирает его
 * из дерева доступности, иначе вспомогательная технология объявляла бы
 * безымянную картинку вместо названия преимущества (разд. 4.5).
 *
 * @shared: imolt-miniapp
 * @adr: ADR-0008
 */
import type { ReactNode } from 'react';
import { space } from './tokens';

/**
 * Толщина контура — та же, что у значков оболочки и значков статуса
 * (разд. 4.4). Отдельной роли под неё в токенах нет: `stroke.hairline` — это
 * рамка управления в один пиксель, а `stroke.emphasis` — кольцо фокуса в два.
 */
const LINE = 1.5;

/** Сторона рисунка: он соразмерен заголовку карточки, а не картинке. */
const SIZE = space.xxl;

/** Что именно объясняет карточка. */
export type IllustrationKind = 'transport' | 'route' | 'statuses' | 'demolition' | 'interior' | 'excavation' | 'metal';

const DRAWINGS: Record<IllustrationKind, ReactNode> = {
  // Самосвал с кузовом: перевозка — первая из двух слагаемых цены (R-019).
  transport: (
    <>
      <rect x="3" y="11" width="18" height="15" rx="2.5" />
      <path d="M21 16h6.2l5.8 5.8V26H21z" />
      <circle cx="11" cy="29.5" r="3" />
      <circle cx="27" cy="29.5" r="3" />
      <path d="M2 32.5h36" />
    </>
  ),
  // Дорога от точки вывоза до площадки: расстояние считается по дорожной
  // сети, а не по прямой (R-023), и кривая линия говорит об этом сразу.
  route: (
    <>
      <circle cx="9" cy="31" r="3" />
      <circle cx="31" cy="9" r="3" />
      <path d="M9 28C9 19 31 21 31 12" />
    </>
  ),
  // Календарный лист со знаком подтверждения: у цены и статуса названа дата
  // актуальности (R-048).
  statuses: (
    <>
      <rect x="6" y="8" width="28" height="26" rx="3" />
      <path d="M6 16h28" />
      <path d="M14 4.5V11M26 4.5V11" />
      <path d="M14.5 24.5l4 4 7.5-8" />
    </>
  ),
  // Экскаватор-разрушитель со стрелой над зданием: механизированный снос
  // целого объёма (выполненные проекты, R-087).
  demolition: (
    <>
      <rect x="4" y="18" width="13" height="14" />
      <path d="M4 22h13M4 26h13" />
      <path d="M21 32V22l8-11 4 2-6 11" />
      <path d="M19 32h18" />
      <path d="M31 6.5l3.5 2.5" />
    </>
  ),
  // Стены и перекрытия внутри контура здания: разборка изнутри, когда
  // наружная коробка остаётся.
  interior: (
    <>
      <rect x="6" y="7" width="28" height="26" rx="2" />
      <path d="M13 33V17h9v16" />
      <path d="M22 22h8" />
      <path d="M6 17h7" />
    </>
  ),
  // Ковш над откосом котлована: вывоз грунта объёмом, а не разбор строения.
  excavation: (
    <>
      <path d="M3 30h9l6-9h14l5 9" />
      <path d="M12 30h25" />
      <path d="M24 8v7M24 15l-5 6M24 15l5 6" />
      <path d="M19 21h10" />
    </>
  ),
  // Балка под резаком: разделка металла в габарит перед вывозом.
  metal: (
    <>
      <path d="M5 14h30v6H5z" />
      <path d="M5 26h30" />
      <path d="M20 20v6" />
      <path d="M13 31l4-5M27 31l-4-5" />
    </>
  ),
};

export function Illustration({ kind, className }: { kind: IllustrationKind; className?: string }) {
  return (
    <svg
      className={className ? `imolt-illustration ${className}` : 'imolt-illustration'}
      width={SIZE}
      height={SIZE}
      viewBox="0 0 40 40"
      fill="none"
      // Цвет назначает карточка ролью из токенов: рисунок своего цвета не
      // имеет и потому не расходится с текстом рядом (ADR-0008, инвариант 1).
      stroke="currentColor"
      strokeWidth={LINE}
      strokeLinecap="round"
      strokeLinejoin="round"
      aria-hidden="true"
    >
      {DRAWINGS[kind]}
    </svg>
  );
}
