/**
 * Цвета линий маршрута по порядку полигонов.
 *
 * Линия одного цвета при нескольких выбранных полигонах не различается:
 * пути идут рядом и сливаются в один (замечание заказчика от 25.09.2026).
 * Цвет здесь — не смысл, а связь: тем же цветом помечена метка полигона на
 * карте и точка в его строке перечня, а что это за полигон, говорит подпись
 * рядом (карточка практики PRACT-029).
 *
 * Порядок начинается с чёрного: у одного полигона вид карты не меняется.
 */
export const routeTones = [
  palette.routeInk,
  palette.routeViolet,
  palette.routeTeal,
  palette.routeBrown,
  palette.routeIndigo,
] as const;

/** Цвет маршрута по месту полигона в перечне; цвета идут по кругу. */
export function routeTone(index: number): string {
  return routeTones[index % routeTones.length] ?? routeTones[0];
}

