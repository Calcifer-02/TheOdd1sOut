/**
 * Разделы сервиса: единственный перечень переходов оболочки.
 *
 * Перечень объявлен один раз и одинаков для широкого и узкого представления:
 * два списка разошлись бы, и на телефоне рано или поздно не хватило бы
 * раздела, который на рабочем месте есть (карточка практики PRACT-016).
 *
 * @supports: R-058
 * @adr: ADR-0008
 */
import { CALCULATOR_PATH } from '@/shared/lib/routing';

export type Section = {
  path: string;
  label: string;
  /**
   * Раздел живёт только в нижней панели телефона, а в шапочный перечень не
   * попадает.
   *
   * Признак нужен одному разделу — кабинету. На рабочем месте в кабинет ведёт
   * профиль участника справа в шапке, и пункт перечня рядом с ним был бы
   * вторым входом в тот же экран в той же шапке (BUG-009). На телефоне
   * профиль стоит у верхней кромки, до которой большой палец не достаёт, —
   * ровно та причина, по которой нижняя панель вообще существует, поэтому там
   * раздел остаётся.
   */
  phoneOnly?: boolean;
};

/** Адрес кабинета: в него ведут и нижняя панель, и профиль в шапке. */
export const CABINET_PATH = '/cabinet';

/** Порядок — порядок пути пользователя: расчёт, полигоны, предложение, учёт. */
export const SECTIONS: Section[] = [
  { path: CALCULATOR_PATH, label: 'Расчёт' },
  { path: '/landfills', label: 'Полигоны' },
  { path: '/quote', label: 'Предложение' },
  { path: CABINET_PATH, label: 'Кабинет', phoneOnly: true },
  { path: '/references', label: 'Редактор цен' },
];

/**
 * Горизонтальный перечень шапки — производная единственного перечня, а не
 * второй список: второй список разошёлся бы с первым молча.
 */
export const TOP_SECTIONS: Section[] = SECTIONS.filter((section) => !section.phoneOnly);

/** Доступное имя перечня переходов. Оболочка называет его обоим представлениям. */
export const NAVIGATION_LABEL = 'Разделы сервиса';
