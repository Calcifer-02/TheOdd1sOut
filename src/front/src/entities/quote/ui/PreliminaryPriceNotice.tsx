/**
 * Отметка о предварительности цены.
 *
 * Предварительность названа словом, а не подразумевается оговоркой мелким
 * шрифтом: требование R-059 прямо требует пометки, и в документе она тоже
 * печатается. Формулировка взята из дизайн-договора (разд. 5, Э-07).
 *
 * Допустимое отклонение финальной цены заказчиком не названо (Q-010), поэтому
 * порог назван словом «согласованный», а не числом: выдуманный процент был бы
 * обещанием, которого никто не давал.
 *
 * @supports: R-059, R-038
 * @adr: ADR-0008
 */
import { formatDate } from '@/shared/lib/formatting';

export function PreliminaryPriceNotice({
  validUntil,
}: {
  /** Срок действия цены; `null` — предложение ещё не выпущено. */
  validUntil: string | null;
}) {
  return (
    <p className="imolt-quote-note">
      <strong>Цена предварительная</strong>, отклонение финальной – в пределах согласованного
      порога. Стоимость пересчитывается при изменении фактического объёма, состава отходов или
      статуса приёма полигоном. Предложение не является публичной офертой.
      {validUntil !== null && (
        <>
          {' '}
          Цена закреплена до <time dateTime={validUntil}>{formatDate(validUntil)}</time>.
        </>
      )}
    </p>
  );
}
