/**
 * Объяснение закрытой правки справочника: почему чтение открыто, почему
 * правка закрыта и что её открывает.
 *
 * Устройство доступа такое. Своего входа у сервиса нет — личность даёт
 * платформа MAX (ADR-0006), и приходит она вместе с запуском мини-приложения
 * из переписки с чат-ботом. Мини-приложение при этом открывается и в обычном
 * браузере: тогда участник не опознан, справочник цен читается целиком, а
 * правка закрыта. Внутри MAX участник опознан, и правка доступна тому, кому
 * выдано право ведения справочников (ADR-0007).
 *
 * Слова службы это устройство не объясняют: на отказ по сессии она отвечает
 * действием «откройте мини-приложение в MAX», а мини-приложение уже открыто —
 * заказчик прочитал это как противоречие (BUG-012). Поэтому причину называет
 * экран, а текст живёт в предметной части: представлений у экрана два, и
 * вторая копия объяснения разошлась бы с первой молча.
 *
 * Дом текста — сущность «участник», а не экран: объяснение нужно и редактору
 * цен, и форме отзыва в справочнике полигонов, а два слайса слоя экранов друг
 * к другу подключаться не вправе. Речь здесь о личности участника и его
 * праве — это и есть предмет этой сущности.
 *
 * @supports: R-050, R-042
 * @adr: ADR-0006
 */
import { ApiProblem } from '@/shared/api/http';
import { AUTHENTICATION_REQUIRED, ROLE_REQUIRED, type Refusal } from '@/shared/api/maintenance';

/**
 * Почему чтение осталось открытым. Одна строка на оба отказа: разграничение
 * касается правки, а не просмотра (R-050).
 */
export const READING_OPEN =
  'Справочник цен остаётся открытым: чтение не требует ни личности, ни права – закрыта только правка.';

/**
 * Почему правка закрыта, когда участник не опознан, и что её открывает.
 * Про вход по телефону, коду или паролю здесь не говорится: такого входа у
 * сервиса нет и не будет (ADR-0006, снятое решение R-066).
 */
export const IDENTITY_FROM_MAX =
  'Своего входа у сервиса нет: участника опознаёт платформа MAX – личность приходит вместе с ' +
  'запуском мини-приложения из переписки с чат-ботом. Пока сервис не знает, кто пришёл, менять ' +
  'цены нельзя; правку открывает опознанный участник с правом ведения справочников.';

/**
 * Почему правка закрыта, когда право ведения справочников не выдано. Служба
 * называет эту причину сама, и её слова остаются на экране; строка нужна на
 * случай отказа без пояснения.
 */
export const RIGHT_FROM_OWNER =
  'Личность сервис знает, а права ведения справочников у этого участника нет: правку открывает ' +
  'право, выданное владельцем данных.';

/**
 * Строки объяснения под заголовком отказа: сначала причина закрытой правки,
 * следом — почему чтение осталось открытым.
 */
export function accessExplanation(refusal: Refusal): string[] {
  if (refusal.type === AUTHENTICATION_REQUIRED) {
    return [IDENTITY_FROM_MAX, READING_OPEN];
  }

  return [refusal.detail ?? RIGHT_FROM_OWNER, READING_OPEN];
}

/**
 * Короткая причина для панели обновления справочников. Отказ по сессии
 * приходит и сюда, и в объяснение выше; повторять полное объяснение на одном
 * экране дважды — шум, поэтому панель называет только своё ограничение.
 */
export function runRefusalReason(refusal: Refusal): string {
  return refusal.type === AUTHENTICATION_REQUIRED
    ? 'Итог последнего обновления виден опознанному участнику: сейчас сервис не знает, кто пришёл.'
    : 'Итог последнего обновления виден участнику с правом ведения справочников.';
}

/**
 * Объяснение отказа по доступу для экрана, который показывает отказ одной
 * строкой. Возвращает пустую строку, если отказ не про личность и не про
 * право: тогда объяснять нечего, и слова службы остаются как есть.
 *
 * Нужно форме отзыва в справочнике полигонов: до этого она показывала один
 * заголовок «Нужна сессия участника» без причины (BUG-012).
 */
export function accessRefusalLine(error: unknown): string {
  if (!(error instanceof ApiProblem)) {
    return '';
  }

  if (error.type === AUTHENTICATION_REQUIRED) {
    return `${IDENTITY_FROM_MAX} ${READING_OPEN}`;
  }

  if (error.type === ROLE_REQUIRED) {
    return `${RIGHT_FROM_OWNER} ${READING_OPEN}`;
  }

  return '';
}
