namespace Imolt.Bot.Domain;

/// Учётная запись самого чат-бота на платформе: то, чем он представляется и
/// из чего складывается кнопка открытия мини-приложения (R-069).
///
/// Значения не пишутся в код: их отдаёт платформа по запросу о себе. Бот у
/// проекта может смениться, а выпущенные сообщения останутся со старым
/// составом кнопки (ADR-0009, раздел последствий).
///
/// @req: R-069
/// @adr: ADR-0009
public sealed record BotIdentity(string Username, long ContactId);

/// Команда чат-бота: имя, которое участник набирает, и пояснение, которое
/// платформа показывает рядом.
///
/// @supports: R-070
public sealed record BotCommand(string Name, string Description);
