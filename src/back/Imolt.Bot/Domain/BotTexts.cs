using System.Text;

namespace Imolt.Bot.Domain;

/// Тексты чат-бота и перечень его команд (R-070, R-061).
///
/// Держатся одним местом: те же слова показывает платформа в перечне команд и
/// бот в первом сообщении, и разойтись они не должны. Предметные имена — из
/// глоссария проекта.
///
/// @req: R-070
/// @adr: ADR-0009
public static class BotTexts
{
  /// Команды, о которых бот объявляет платформе. Перечень закрытый: бот
  /// распознаёт ровно то, что называет (AC-070a).
  public static IReadOnlyList<BotCommand> Commands { get; } =
  [
    new("start", "Начать работу и открыть расчёт"),
    new("calculate", "Открыть расчёт вывоза в мини-приложении"),
    new("help", "Что умеет этот чат-бот"),
  ];

  /// Подпись кнопки открытия мини-приложения.
  public const string OpenAppLabel = "Рассчитать вывоз";

  /// Что чат-бот умеет — перечень возможностей первого сообщения. Порядок
  /// повторяет путь участника: вход в мини-приложение, короткое действие в
  /// переписке, справка, извещения (карта пути пользователя, этапы 1 и 7).
  ///
  /// Объявлен раньше приветствия намеренно: статические поля выполняются
  /// сверху вниз, и перечень, объявленный ниже, оказался бы при сборке
  /// приветствия ещё пустым.
  private static IReadOnlyList<string> Abilities { get; } =
  [
    "открыть расчёт вывоза в мини-приложении — кнопкой под этим сообщением",
    "назвать предварительную совокупную цену по адресу вывоза и объёму одной группы отходов",
    "ответить о тарифе полигона и коэффициенте плотности группы отходов значением из справочника сервиса",
    "известить о смене статуса заявки на вывоз",
  ];

  /// Первое сообщение переписки: одно, с перечнем команд и кнопкой.
  /// Повторно не отправляется (AC-070b).
  ///
  /// Собирается из того же перечня `Commands`, который уходит платформе:
  /// второе место с именами команд разошлось бы с первым, и участник узнал бы
  /// о команде, которой бот не объявлял.
  ///
  /// Знак «/» в тексте стоит только перед объявленной командой. Адрес
  /// мини-приложения в приветствие не подставляется: вход даёт кнопка, а
  /// адрес платформа берёт из настроек бота (ADR-0009, инвариант 1).
  public static string Greeting { get; } = ComposeGreeting();

  /// Ответ на прямой вопрос «что умеет этот чат-бот» (команда `help`).
  ///
  /// Перечня команд здесь нет намеренно: однажды объявленный перечень в
  /// переписке не повторяется (AC-070b), а молчать в ответ на прямой вопрос
  /// участника — дефект. Поэтому ответ называет возможности и отсылает к
  /// первому сообщению переписки.
  public static string Help { get; } = ComposeHelp();

  private static string ComposeGreeting()
  {
    var text = new StringBuilder();

    text.AppendLine("Чат-бот ИМОЛТ считает вывоз и утилизацию отходов строительства и сноса");
    text.AppendLine("по Москве и Московской области.");
    text.AppendLine();
    text.AppendLine("Что умеет чат-бот:");

    foreach (var ability in Abilities)
    {
      text.Append("— ").Append(ability).AppendLine(";");
    }

    text.AppendLine();
    text.AppendLine("Команды чат-бота:");

    foreach (var command in Commands)
    {
      text.Append('/').Append(command.Name).Append(" — ").AppendLine(command.Description);
    }

    return text.ToString().TrimEnd();
  }

  private static string ComposeHelp()
  {
    var text = new StringBuilder();

    text.AppendLine("Что умеет чат-бот:");

    foreach (var ability in Abilities)
    {
      text.Append("— ").Append(ability).AppendLine(";");
    }

    text.AppendLine();
    text.Append("Перечень команд чат-бот показал в первом сообщении переписки.");

    return text.ToString();
  }
}
