-- Права участника: что ему разрешено в сервисе (ADR-0007).
--
-- Уточнение к комментарию СУЩ-13 в 0001: там участник описан как «перевозчик,
-- демонтажная компания или менеджер данных», будто это три значения одной
-- колонки. Файл 0001 уже применён, и его отпечаток записан в schema_migration,
-- поэтому правка идёт сюда, а не туда.
--
-- Разделение сделано не ради стройности. Колонка subscriber.role заполняется
-- заявкой на подписку, которую участник подаёт сам (R-051). Будь право
-- третьим значением той же колонки, обычная заявка на подписку молча снимала
-- бы у сотрудника право править цены.
--
-- Право отделено и от личности: маркер доступа прав не несёт, они читаются
-- при каждом запросе. Отозванное право действует со следующего запроса, а не
-- до конца срока маркера (ADR-0007, инвариант 1).
create table if not exists subscriber_permission (
    subscriber_id uuid        not null references subscriber (id) on delete cascade,
    -- Перечень задан CHECK, как и прочие в этой схеме: значение в ENUM нельзя
    -- убрать внутри транзакции, и миграция перестаёт быть отменяемой.
    permission    text        not null check (permission in ('manageReferences')),
    granted_at    timestamptz not null,
    primary key (subscriber_id, permission)
);
