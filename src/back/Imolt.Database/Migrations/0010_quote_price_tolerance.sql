-- Допустимое отклонение окончательной цены в снимке предложения (R-059).
--
-- Зачем. Отклонение печатается в документе, а документ собирается из снимка:
-- предложение, пересчитанное по сегодняшней настройке, назвало бы клиенту
-- другое число, чем то, на котором оно выпущено. Настройка меняется, а
-- выпущенное предложение — нет.
--
-- Столбец допускает пустое значение намеренно: предложения, выпущенные до
-- решения команды по Q-010 от 25.09.2026, условия отклонения не несли, и
-- приписывать им сегодняшнее число задним числом нельзя. Документ таких
-- предложений печатает отметку о предварительности без величины.
--
-- Значения по умолчанию здесь нет: число живёт настройкой службы, и второе
-- его место — в схеме — разошлось бы с первым молча.

alter table quote
  add column if not exists price_tolerance_percent numeric(5, 2);

comment on column quote.price_tolerance_percent is
  'Допустимое отклонение окончательной цены от предварительной, проценты (R-059)';
