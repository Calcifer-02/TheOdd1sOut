-- Два уточнения схемы под область «сделка».
--
-- Первое. Срок действия цены становится обязательным. Договор объявляет
-- validUntil обязательным полем схемы Quote, а колонка была обнуляемой с
-- пометкой «не назначается, пока заказчик не ответил на Q-010». Оба
-- утверждения одновременно невыполнимы. Открытый вопрос Q-010 касается
-- длительности срока, а не того, есть ли он вовсе: срок печатается в
-- документе всегда (R-038), а его величина берётся настройкой службы.
--
-- Второе. Цена услуги по документации и признак «по запросу» исключают друг
-- друга. Прежнее ограничение требовало «хотя бы одного из двух» и пропускало
-- карточку, где названа и цена, и «уточняйте», — такая карточка не сообщает
-- клиенту ничего (R-052).
--
-- @req: R-038, R-052

alter table quote
  alter column valid_until set not null;

alter table document_service
  drop constraint if exists document_service_check;

alter table document_service
  add constraint document_service_price_is_exclusive
  check (price_on_request <> (price_from is not null));

-- Третье. Снимок предложения дополняется тем, что нужно напечатать: имя
-- полигона, наименование группы отходов и введённый объём с мерой. Прежде
-- строка снимка несла только идентификаторы и посчитанные суммы, и документ
-- пришлось бы собирать из справочников — то есть из данных, которые к моменту
-- скачивания уже изменились. Снимок, зависящий от справочника, снимком не
-- является (R-036, R-037).

alter table quote_line
  add column if not exists landfill_name    text,
  add column if not exists waste_group_name text,
  add column if not exists unit             text,
  add column if not exists input_value      numeric(12, 3);
