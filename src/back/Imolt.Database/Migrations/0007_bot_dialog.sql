-- Состояние переписки участника с чат-ботом (ADR-0009, инвариант 5).
--
-- Таблица заведена потому, что переписка перестала быть хранилищем: чат-бот
-- ведёт одну карточку и переписывает её, а свои прежние сообщения сверх
-- предела удаляет (R-078, R-079). Всё, что обязано пережить удаление
-- сообщения, живёт здесь: какая карточка ведётся и какие сообщения
-- принадлежат боту (R-080).
create table if not exists bot_dialog (
    -- Идентификатор переписки платформы. Ключ естественный: своего
    -- суррогатного идентификатора у переписки нет, а платформенный
    -- единственный и неизменный.
    chat_id            bigint      primary key,
    -- Идентификатор ведущейся карточки. Текст, а не число: платформа
    -- объявляет идентификатор сообщения строкой.
    card_message_id    text,
    -- Идентификаторы сообщений самого бота, от ранних к поздним. Массив, а не
    -- отдельная таблица: перечень короткий по построению — длиннее предела
    -- глубины он не бывает, и читается он всегда целиком.
    own_message_ids    text[]      not null default '{}',
    -- Перечень команд уже отправлен: повторно он не показывается (R-070).
    commands_announced boolean     not null default false,
    updated_at         timestamptz not null
);

-- Связь переписки с участником (R-071).
--
-- Колонка заведена у участника, а не у переписки, намеренно. У таблицы
-- bot_dialog один писатель — чат-бот, который ведёт свои сообщения; связь же
-- возникает в другом месте и в другое время: её узнаёт расчётная часть, когда
-- проверит подпись стартовых параметров мини-приложения. Два писателя в одну
-- таблицу означали бы, что владельца у неё нет.
--
-- Значение необязательно и появляется не сразу: участник существует с первого
-- входа, а переписка становится известна, только когда приложение открыто
-- именно из неё. Отсутствие связи — нормальное состояние, а не ошибка.
alter table subscriber
    add column if not exists max_chat_id bigint;

create index if not exists subscriber_max_chat_idx on subscriber (max_chat_id);
