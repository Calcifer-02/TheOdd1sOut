namespace Imolt.Shared;

/// Время приходит в домен портом, а не системным вызовом: иначе расчёт
/// перестаёт воспроизводиться, а проверка сезонного коэффициента зависит от
/// дня, когда её запустили (правило ARCH-025).
///
/// @shared: imolt-shared
/// @adr: ADR-0005
public interface IClock
{
  DateTimeOffset Now { get; }

  DateOnly Today { get; }

  /// Начало суток службы. Календарь дня принадлежит часам: всякий, кому нужны
  /// границы дня, берёт их здесь, а не пересчитывает пояс у себя. Иначе номер
  /// документа считается по одному дню, а счётчик выпущенных за день — по
  /// другому, и расхождение видно только в окно между полуночью службы и
  /// полуночью UTC.
  DateTimeOffset StartOfDay(DateOnly day);
}
