#!/usr/bin/env node
// Перестраивает производные колонки реестра требований из отчёта
// трассируемости: «Файл / модуль» — по якорям @req и @supports в коде,
// «Критерий приёмки / проверка» дополняется тем, что якоря @ac реально
// закрывают проверками.
//
// Колонки объявлены в реестре производными: руками их не ведут, потому что
// копия расходится с кодом и начинает врать. Источник — снимок коммита, а не
// рабочее дерево: сканер трассы читает git, и отчёт по незакоммиченным
// файлам получить нельзя.
//
// Запуск на закрытии среза:
//   node tests/traceability/реализация-в-реестр.mjs [--проверить]
//
// Ключ --проверить ничего не пишет, а только сообщает расхождение и
// завершается кодом 1: так его можно поставить барьером.

import { execFileSync } from 'node:child_process';
import { mkdtempSync, readFileSync, writeFileSync, rmSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { join } from 'node:path';

const РЕЕСТР = 'docs/ПАКЕТ_АНАЛИТИКИ/РЕЕСТР_ТРЕБОВАНИЙ.md';
const СРЕДСТВО = '.trip/tools/trip-cli/trip.exe';
const КОЛОНКА_ФАЙЛОВ = 17;
const ТОЛЬКО_ПРОВЕРКА = process.argv.includes('--проверить');

function снятьОтчёт() {
  const каталог = mkdtempSync(join(tmpdir(), 'imolt-trace-'));
  const путь = join(каталог, 'trace.json');
  const голова = execFileSync('git', ['rev-parse', 'HEAD'], { encoding: 'utf8' }).trim();

  try {
    try {
      execFileSync(СРЕДСТВО, ['trace', 'scan', '--mode', 'full', '--head', голова, '--output', путь], {
        stdio: 'ignore',
      });
    } catch (отказ) {
      // Коды 0 и 2 — «чисто» и «есть предупреждения»: отчёт при них написан.
      // Всё остальное — настоящий отказ средства, и отчёта нет.
      if (отказ.status !== 2) throw отказ;
    }

    return JSON.parse(readFileSync(путь, 'utf8'));
  } finally {
    rmSync(каталог, { recursive: true, force: true });
  }
}

// Якоря лежат в отчёте вложенно и без устойчивого пути: ищем по ключу.
function собратьЯкоря(узел, собранное = []) {
  if (Array.isArray(узел)) {
    for (const элемент of узел) собратьЯкоря(элемент, собранное);
  } else if (узел && typeof узел === 'object') {
    if (Array.isArray(узел.anchors)) собранное.push(...узел.anchors);
    for (const значение of Object.values(узел)) собратьЯкоря(значение, собранное);
  }
  return собранное;
}

function реализацияПоТребованиям(якоря) {
  const поТребованию = new Map();

  for (const якорь of якоря) {
    for (const требование of якорь.requirementIds ?? []) {
      const пути = поТребованию.get(требование) ?? new Map();
      // Реализация и обслуживание различаются: первое закрывает требование,
      // второе только помогает. Один файл может нести оба якоря — тогда
      // побеждает реализация, иначе строка реестра читается как «только
      // обслуживает», хотя требование закрыто.
      const реализует = якорь.classification === 'implements';
      пути.set(якорь.path, (пути.get(якорь.path) ?? false) || реализует);
      поТребованию.set(требование, пути);
    }
  }

  return поТребованию;
}

// Требование считается проверенным, когда критерий приёмки закрыт кодом
// проверки: якорь @ac в проверочной области именует AC-id, а его номер и есть
// номер требования (соглашение вида «Приёмочные тесты»).
function проверенные(якоря) {
  const собранное = new Set();

  for (const якорь of якоря) {
    for (const критерий of якорь.acceptanceCriterionIds ?? []) {
      const совпадение = /^AC-(\d{3})[a-z]$/.exec(критерий);
      if (совпадение) собранное.add('R-' + совпадение[1]);
    }
  }

  return собранное;
}

// Одно слово ответа на вопрос «что из требований уже работает». В таблицу
// реестра оно не добавляется: состав колонок задан схемой вида артефакта и
// правится методологией, а не проектом. Слово печатается сводкой прогона.
function состояниеРеализации(пути, проверено) {
  const естьКод = пути ? [...пути.values()].some(Boolean) : false;

  if (естьКод && проверено) return 'реализовано';
  if (естьКод) return 'код без проверки';
  if (проверено) return 'проверка без кода';
  if (пути) return 'обслуживается';
  return '—';
}

const отчёт = снятьОтчёт();
const якоря = собратьЯкоря(отчёт);
const реализация = реализацияПоТребованиям(якоря);
const сПроверкой = проверенные(якоря);

const строки = readFileSync(РЕЕСТР, 'utf8').split('\n');
const расхождения = [];
let изменено = 0;

for (let i = 0; i < строки.length; i += 1) {
  if (!/^\|\s*\d+\s*\|\s*R-\d{3}\s*\|/.test(строки[i])) continue;

  const поля = строки[i].split('|');
  const требование = поля[2].trim();
  const пути = реализация.get(требование);
  const нужно = пути
    ? ` ${[...пути.entries()]
        .map(([путь, реализует]) => путь + (реализует ? '' : ' (обслуживает)'))
        .sort()
        .join('<br>')} `
    : ' — ';

  if (поля[КОЛОНКА_ФАЙЛОВ] === нужно) continue;

  расхождения.push(`${требование}: «${поля[КОЛОНКА_ФАЙЛОВ].trim()}» → «${нужно.trim()}»`);
  поля[КОЛОНКА_ФАЙЛОВ] = нужно;
  строки[i] = поля.join('|');
  изменено += 1;
}

if (ТОЛЬКО_ПРОВЕРКА) {
  if (расхождения.length === 0) {
    console.log('Производная колонка реестра совпадает с якорями кода.');
    process.exit(0);
  }

  console.log(`Производная колонка разошлась с якорями кода, строк: ${расхождения.length}`);
  for (const расхождение of расхождения) console.log('  ' + расхождение);
  console.log('Перестроить: node tests/traceability/реализация-в-реестр.mjs');
  process.exit(1);
}

if (изменено > 0) writeFileSync(РЕЕСТР, строки.join('\n'), 'utf8');

const сТребованием = [...реализация.keys()].sort();
const реализовано = сТребованием.filter((т) => состояниеРеализации(реализация.get(т), сПроверкой.has(т)) === 'реализовано');
console.log(`Требований со словом «реализовано»: ${реализовано.length}`);
console.log(`Требований, затронутых кодом: ${сТребованием.length}`);
console.log(`Строк реестра перестроено: ${изменено}`);
for (const требование of сТребованием) {
  console.log(`  ${требование}: ${[...реализация.get(требование).entries()]
    .map(([путь, реализует]) => путь + (реализует ? '' : ' (обслуживает)'))
    .sort()
    .join(', ')}`);
}
