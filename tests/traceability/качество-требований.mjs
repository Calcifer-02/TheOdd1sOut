#!/usr/bin/env node
// Сверяет объявленные в реестре характеристики требования с его текстом.
//
// Колонки «КК» реестра — характеристики требования по ISO/IEC/IEEE 29148
// (они же у Виггерса): завершённое, атомарное, непротиворечивое, однозначное,
// необходимое, тестируемое, реализуемое. Проставлены они вручную, и «Да»
// у каждой строки ничего не значит, пока никто не сверил его с текстом.
//
// Проверяются только машинно наблюдаемые признаки — там, где нарушение видно
// из самой формулировки. Остальное остаётся человеку и профильному ревью:
// средство, притворяющееся арбитром смысла, хуже отсутствующего.
//
//   node tests/traceability/качество-требований.mjs [--строго]
//
// Без ключа печатает находки и завершается успехом: это срез состояния.
// С ключом --строго завершается отказом, если объявленное «Да» противоречит
// найденному, — так проверку можно поставить барьером.

import { readFileSync } from 'node:fs';

const РЕЕСТР = 'docs/ПАКЕТ_АНАЛИТИКИ/РЕЕСТР_ТРЕБОВАНИЙ.md';
const СТРОГО = process.argv.includes('--строго');

const КОЛОНКИ = {
  идентификатор: 2,
  уровень: 4,
  текст: 5,
  класс: 10,
  статус: 11,
  критерии: 20,
  завершённое: 22,
  атомарное: 23,
  однозначное: 25,
  тестируемое: 27,
};

// Слова без меры: «быстро» и «удобно» нельзя ни подтвердить, ни опровергнуть.
// Числовая граница рядом снимает возражение — тогда требование измеримо.
const СЛАБЫЕ_СЛОВА = [
  'быстро', 'удобно', 'просто', 'легко', 'оптимально', 'эффективно',
  'по возможности', 'при необходимости', 'и т. д.', 'и т.д.', 'и т. п.', 'и т.п.',
  'регулярно', 'своевременно', 'минимально', 'максимально', 'достаточно',
  'гибко', 'надёжно', 'качественно', 'понятно', 'наглядно',
];

const ЧИСЛО_РЯДОМ = /\d/;

// Перечисление свойств в одной строке: требование описывает не одно
// наблюдаемое свойство, а список. Разделители считаются в определяющей части,
// после двоеточия, — там, где перечисляют состав.
function перечислено(текст) {
  const послеДвоеточия = текст.includes(':') ? текст.slice(текст.indexOf(':') + 1) : текст;
  const запятые = (послеДвоеточия.match(/,/g) ?? []).length;
  const точкиСЗапятой = (послеДвоеточия.match(/;/g) ?? []).length;
  return запятые + точкиСЗапятой * 2;
}

const строки = readFileSync(РЕЕСТР, 'utf8').split('\n');
// Шаблоны EARS в русской записи. Форма даёт ровно один отклик и ровно одно
// условие, поэтому неатомарное требование в неё не помещается: это проверка
// причины, а не следствия, которое ловит подсчёт перечислений.
// Форма связки перечислена целиком: субъектом бывает и «сервис», и
// «чат-бот», и «расчётная часть», а род субъекта задаёт окончание. Сокращение
// до «должн[аоы]?» пропускало мужской род и занижало долю соблюдения.
const ШАБЛОНЫ = [
  { имя: 'по событию', образец: /^Когда .+, .+ долж(?:ен|на|но|ны) .+$/ },
  { имя: 'в состоянии', образец: /^Пока .+, .+ долж(?:ен|на|но|ны) .+$/ },
  { имя: 'нежелательное', образец: /^Если .+, то .+ долж(?:ен|на|но|ны) .+$/ },
  { имя: 'при включённой возможности', образец: /^Где .+, .+ долж(?:ен|на|но|ны) .+$/ },
  { имя: 'всегда', образец: /^(?!Когда |Пока |Если |Где ).+ долж(?:ен|на|но|ны) .+$/ },
];

function поШаблону(текст) {
  return ШАБЛОНЫ.find((шаблон) => шаблон.образец.test(текст))?.имя;
}

const находки = [];
const противоречия = [];
const пробелы = [];
const шаблонных = new Set();
const всего = new Set();

for (const строка of строки) {
  if (!/^\|\s*\d+\s*\|\s*R-\d{3}\s*\|/.test(строка)) continue;

  const поля = строка.split('|');
  const требование = поля[КОЛОНКИ.идентификатор].trim();
  const текст = поля[КОЛОНКИ.текст].trim();
  const класс = поля[КОЛОНКИ.класс].trim();
  const статус = поля[КОЛОНКИ.статус].trim();
  const уровень = поля[КОЛОНКИ.уровень].trim();
  const критерии = поля[КОЛОНКИ.критерии].trim();

  const объявлено = (имя) => поля[КОЛОНКИ[имя]].trim() === 'Да';
  const добавить = (характеристика, повод) => {
    находки.push({ требование, характеристика, повод });
    if (объявлено(характеристика)) {
      противоречия.push(`${требование}: «${характеристика} = Да», но ${повод}`);
    }
  };

  // Соблюдение шаблона. Требование вне шаблона не отвергается: соглашение
  // принято 23.09.2026 и действует для новых и переписываемых формулировок,
  // а унаследованные переписываются по мере работы с ними.
  всего.add(требование);
  if (поШаблону(текст)) шаблонных.add(требование);

  // Однозначность. Слабое слово без числовой границы рядом делает требование
  // непроверяемым: спорить о нём можно бесконечно.
  const нижний = текст.toLowerCase();
  const слабые = СЛАБЫЕ_СЛОВА.filter((слово) => нижний.includes(слово));
  if (слабые.length > 0 && !ЧИСЛО_РЯДОМ.test(текст)) {
    добавить('однозначное', `в формулировке слово без меры: ${слабые.join(', ')}`);
  }

  // Атомарность. Три и более перечисленных свойства — это не одно требование,
  // а список, и закрыть его целиком нельзя: часть будет сделана, часть нет.
  const свойств = перечислено(текст);
  if (свойств >= 3) {
    добавить('атомарное', `в определяющей части перечислено свойств: ${свойств + 1}`);
  }

  // Покрытие критерием приёмки — не характеристика требования, а состояние
  // работы: отсутствие критерия говорит о пробеле следа, а не о том, что
  // требование непроверяемо в принципе. Поэтому пишется отдельной строкой и
  // в противоречие с объявленным «Да» не ставится.
  if (класс === 'К1' && (критерии === '—' || критерии === '') && статус !== 'отложено') {
    пробелы.push(`${требование}: класс К1, критерия приёмки нет`);
  }

  // Завершённость зонтичных уровней. Требование L0 или L1 закрывается через
  // раскрывающие его требования, а не напрямую: пометка «реализовано» у него
  // означает, что реализацию приписали цели.
  if ((уровень === 'L0' || уровень === 'L1') && статус === 'реализовано') {
    добавить('завершённое', `требование уровня ${уровень} помечено реализованным напрямую`);
  }
}

const поХарактеристике = new Map();
for (const находка of находки) {
  поХарактеристике.set(находка.характеристика, (поХарактеристике.get(находка.характеристика) ?? 0) + 1);
}

console.log(`Требований в форме EARS: ${шаблонных.size} из ${всего.size}`);
console.log(`Требований с наблюдаемым нарушением характеристики: ${new Set(находки.map((н) => н.требование)).size}`);
for (const [характеристика, сколько] of [...поХарактеристике].sort()) {
  console.log(`  ${характеристика}: ${сколько}`);
}
console.log();
for (const находка of находки) {
  console.log(`${находка.требование}  ${находка.характеристика}: ${находка.повод}`);
}

if (пробелы.length > 0) {
  console.log();
  console.log(`Требований класса К1 без критерия приёмки: ${пробелы.length}`);
  for (const пробел of пробелы) console.log('  ' + пробел);
}

if (противоречия.length > 0) {
  console.log();
  console.log(`Объявленное расходится с найденным, строк: ${противоречия.length}`);
  for (const противоречие of противоречия) console.log('  ' + противоречие);
}

// Отказ даётся только на противоречии: само нарушение — предмет разбора с
// аналитиком, а вот «Да» рядом с ним уже утверждение, которое неверно.
process.exit(СТРОГО && противоречия.length > 0 ? 1 : 0);
