#!/usr/bin/env node
// Сверяет ссылки между тремя реестрами аналитики: требований (`R-id`),
// открытых вопросов (`Q-id`) и рисков (`AR-id`).
//
// У каждого вида записи один реестр-владелец, остальные документы на него
// ссылаются (правила проекта, разд. «Продукт и раскладка»). Ссылка на
// незаведённую запись выглядит как связь и связью не является: именно так
// девять сценариев использования полгода значились в реестре требований,
// пока документ-владелец оставался пустым шаблоном.
//
//   node tests/traceability/ссылки-реестров.mjs
//
// Завершается отказом, если хоть одна ссылка ведёт в пустоту. Проверка
// фальсифицируема: переименуйте любой заведённый `Q-id` — падение назовёт
// все требования, которые на него ссылались.

import { readFileSync } from 'node:fs';

const ТРЕБОВАНИЯ = 'docs/ПАКЕТ_АНАЛИТИКИ/РЕЕСТР_ТРЕБОВАНИЙ.md';
const ВОПРОСЫ = 'docs/ПАКЕТ_АНАЛИТИКИ/ОТКРЫТЫЕ_ВОПРОСЫ.md';
const РИСКИ = 'docs/ПАКЕТ_АНАЛИТИКИ/МАТРИЦА_РИСКОВ.md';

// Строка таблицы реестра: первая непустая ячейка — идентификатор записи.
// Строка-образец вида («\_<…>\_») идентификатора не содержит и не попадает
// в выборку сама собой.
function строкиРеестра(файл, образецИдентификатора, колонкаИдентификатора) {
  const строки = readFileSync(файл, 'utf8').split('\n');
  const записи = [];

  for (const строка of строки) {
    if (!строка.startsWith('|')) continue;
    const поля = строка.split('|');
    const идентификатор = поля[колонкаИдентификатора]?.trim() ?? '';
    if (!образецИдентификатора.test(идентификатор)) continue;
    записи.push({ идентификатор, поля });
  }

  return записи;
}

function найденные(текст, образец) {
  return текст.match(образец) ?? [];
}

const требования = строкиРеестра(ТРЕБОВАНИЯ, /^R-\d{3}$/, 2);
const вопросы = строкиРеестра(ВОПРОСЫ, /^Q-\d{3}$/, 1);
const риски = строкиРеестра(РИСКИ, /^AR-\d{3}$/, 1);

const заведено = {
  'R-': new Set(требования.map((з) => з.идентификатор)),
  'Q-': new Set(вопросы.map((з) => з.идентификатор)),
  'AR-': new Set(риски.map((з) => з.идентификатор)),
};

// Колонка «Открытые вопросы» и колонка «Связанные риски» реестра требований;
// колонка «Связанные записи» реестра вопросов; колонка «Фактические связи»
// матрицы рисков. Ячейки читаются целиком: идентификаторы в них перечислены
// через запятую, и разбирать перечисление незачем.
const ссылки = [
  ...требования.map((з) => ({ откуда: з.идентификатор, где: ТРЕБОВАНИЯ, текст: `${з.поля[18]} ${з.поля[19]}` })),
  ...вопросы.map((з) => ({ откуда: з.идентификатор, где: ВОПРОСЫ, текст: з.поля[6] ?? '' })),
  ...риски.map((з) => ({ откуда: з.идентификатор, где: РИСКИ, текст: з.поля[4] ?? '' })),
];

const разрывы = [];

for (const ссылка of ссылки) {
  const названные = [
    ...найденные(ссылка.текст, /\bAR-\d{3}\b/g),
    ...найденные(ссылка.текст, /\bR-\d{3}\b/g),
    ...найденные(ссылка.текст, /\bQ-\d{3}\b/g),
  ];

  for (const названный of new Set(названные)) {
    const вид = названный.startsWith('AR-') ? 'AR-' : названный.slice(0, 2);
    if (!заведено[вид].has(названный)) {
      разрывы.push(`${ссылка.откуда} ссылается на ${названный}, которого нет в реестре-владельце`);
    }
  }
}

console.log(`Заведено записей: требований ${заведено['R-'].size}, вопросов ${заведено['Q-'].size}, рисков ${заведено['AR-'].size}`);
console.log(`Проверено строк со ссылками: ${ссылки.length}`);

if (разрывы.length === 0) {
  console.log('Ссылок в пустоту нет.');
  process.exit(0);
}

console.log();
console.log(`Ссылок в пустоту: ${разрывы.length}`);
for (const разрыв of разрывы) console.log('  ' + разрыв);
process.exit(1);
